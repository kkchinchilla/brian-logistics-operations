-- Increment 1.3.1 / Route catalogue, delivery regions and delivery-price matrix.
-- NON-DESTRUCTIVE. No deletes/truncates to existing business data.
-- Run ONCE in Supabase SQL Editor, then execute 131_02_verify_readonly.sql.
-- SQL editor uses privileged connection; access for browser users is controlled by RLS.
BEGIN;

CREATE TABLE IF NOT EXISTS public.delivery_regions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE CHECK (length(btrim(name)) BETWEEN 1 AND 50),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.delivery_temperature_zones (
  name text PRIMARY KEY CHECK (length(btrim(name)) BETWEEN 1 AND 50),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.delivery_region_zone_rates (
  region_id bigint NOT NULL REFERENCES public.delivery_regions(id) ON DELETE CASCADE,
  zone_name text NOT NULL REFERENCES public.delivery_temperature_zones(name) ON UPDATE CASCADE ON DELETE CASCADE,
  delivery_fee numeric(12,2) NULL CHECK (delivery_fee >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid NULL REFERENCES public.profiles(id),
  PRIMARY KEY(region_id, zone_name)
);
ALTER TABLE public.routes ADD COLUMN IF NOT EXISTS delivery_region_id bigint NULL;
DO $$BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.routes'::regclass AND conname='routes_delivery_region_id_fkey') THEN
    ALTER TABLE public.routes ADD CONSTRAINT routes_delivery_region_id_fkey
      FOREIGN KEY (delivery_region_id) REFERENCES public.delivery_regions(id) ON DELETE RESTRICT;
  END IF;
END$$;
CREATE INDEX IF NOT EXISTS routes_delivery_region_idx ON public.routes(delivery_region_id);

-- Preserve every temperature-zone value already used by legacy routes.
INSERT INTO public.delivery_temperature_zones(name)
SELECT DISTINCT btrim(temperature_zone) FROM public.routes
WHERE temperature_zone IS NOT NULL AND length(btrim(temperature_zone))>0
ON CONFLICT(name) DO NOTHING;

-- New tables: read for all authenticated operators, writes only for dispatchers.
ALTER TABLE public.delivery_regions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.delivery_temperature_zones ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.delivery_region_zone_rates ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS dr_select ON public.delivery_regions;
DROP POLICY IF EXISTS dr_write ON public.delivery_regions;
CREATE POLICY dr_select ON public.delivery_regions FOR SELECT TO authenticated USING (true);
CREATE POLICY dr_write ON public.delivery_regions FOR ALL TO authenticated
  USING ((SELECT private.is_dispatcher())) WITH CHECK ((SELECT private.is_dispatcher()));
DROP POLICY IF EXISTS dtz_select ON public.delivery_temperature_zones;
DROP POLICY IF EXISTS dtz_write ON public.delivery_temperature_zones;
CREATE POLICY dtz_select ON public.delivery_temperature_zones FOR SELECT TO authenticated USING (true);
CREATE POLICY dtz_write ON public.delivery_temperature_zones FOR ALL TO authenticated
  USING ((SELECT private.is_dispatcher())) WITH CHECK ((SELECT private.is_dispatcher()));
DROP POLICY IF EXISTS drz_select ON public.delivery_region_zone_rates;
DROP POLICY IF EXISTS drz_write ON public.delivery_region_zone_rates;
CREATE POLICY drz_select ON public.delivery_region_zone_rates FOR SELECT TO authenticated
  USING ((SELECT private.is_dispatcher()));
CREATE POLICY drz_write ON public.delivery_region_zone_rates FOR ALL TO authenticated
  USING ((SELECT private.is_dispatcher())) WITH CHECK ((SELECT private.is_dispatcher()));
REVOKE ALL ON public.delivery_regions,public.delivery_temperature_zones,public.delivery_region_zone_rates FROM anon;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.delivery_regions,public.delivery_temperature_zones,public.delivery_region_zone_rates TO authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.delivery_regions_id_seq TO authenticated;

-- Never delete a temperature category while an existing route still uses it.
CREATE OR REPLACE FUNCTION public.route_catalog_protect_zone()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF EXISTS(SELECT 1 FROM public.routes WHERE temperature_zone = OLD.name) THEN
    RAISE EXCEPTION '此溫層仍被配送路線使用，無法刪除';
  END IF;
  RETURN OLD;
END$$;
DROP TRIGGER IF EXISTS route_catalog_protect_zone_trigger ON public.delivery_temperature_zones;
CREATE TRIGGER route_catalog_protect_zone_trigger BEFORE DELETE ON public.delivery_temperature_zones
  FOR EACH ROW EXECUTE FUNCTION public.route_catalog_protect_zone();

-- Rename old route references and the zone catalogue atomically in a single RPC call.
CREATE OR REPLACE FUNCTION public.route_catalog_rename_zone(p_old_name text,p_new_name text)
RETURNS void LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE cleaned text := btrim(p_new_name);
BEGIN
  IF NOT (SELECT private.is_dispatcher()) THEN RAISE EXCEPTION '只有主管可以修改溫層'; END IF;
  IF cleaned IS NULL OR length(cleaned) NOT BETWEEN 1 AND 50 THEN RAISE EXCEPTION '溫層名稱需為 1–50 字'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.delivery_temperature_zones WHERE name = p_old_name) THEN
    RAISE EXCEPTION '找不到原始溫層'; END IF;
  IF cleaned = p_old_name THEN RETURN; END IF;
  UPDATE public.delivery_temperature_zones SET name = cleaned WHERE name = p_old_name;
  UPDATE public.routes SET temperature_zone = cleaned WHERE temperature_zone = p_old_name;
END$$;
REVOKE ALL ON FUNCTION public.route_catalog_rename_zone(text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.route_catalog_rename_zone(text,text) TO authenticated;

-- Track historical delivery tariffs to support future service-date pricing snapshots.
CREATE TABLE IF NOT EXISTS public.delivery_region_zone_rate_audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 region_id bigint NOT NULL,
 zone_name text NOT NULL,
 previous_fee numeric(12,2),
 new_fee numeric(12,2),
 action text NOT NULL CHECK (action IN ('INSERT','UPDATE','DELETE')),
 changed_at timestamptz NOT NULL DEFAULT now(),
 changed_by uuid REFERENCES public.profiles(id)
);
ALTER TABLE public.delivery_region_zone_rate_audit ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS drza_read ON public.delivery_region_zone_rate_audit;
CREATE POLICY drza_read ON public.delivery_region_zone_rate_audit FOR SELECT TO authenticated
 USING ((SELECT private.is_dispatcher()));
REVOKE ALL ON public.delivery_region_zone_rate_audit FROM anon,authenticated;
GRANT SELECT ON public.delivery_region_zone_rate_audit TO authenticated;
CREATE OR REPLACE FUNCTION public.route_catalog_rate_audit()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
 IF TG_OP='INSERT' THEN
  INSERT INTO public.delivery_region_zone_rate_audit(region_id,zone_name,previous_fee,new_fee,action,changed_by)
  VALUES(NEW.region_id,NEW.zone_name,NULL,NEW.delivery_fee,'INSERT',auth.uid());
 ELSIF TG_OP='UPDATE' THEN
  INSERT INTO public.delivery_region_zone_rate_audit(region_id,zone_name,previous_fee,new_fee,action,changed_by)
  VALUES(NEW.region_id,NEW.zone_name,OLD.delivery_fee,NEW.delivery_fee,'UPDATE',auth.uid());
 ELSE
  INSERT INTO public.delivery_region_zone_rate_audit(region_id,zone_name,previous_fee,new_fee,action,changed_by)
  VALUES(OLD.region_id,OLD.zone_name,OLD.delivery_fee,NULL,'DELETE',auth.uid());
 END IF;
 RETURN NULL;
END$$;
DROP TRIGGER IF EXISTS delivery_rates_audit ON public.delivery_region_zone_rates;
CREATE TRIGGER delivery_rates_audit AFTER INSERT OR UPDATE OR DELETE ON public.delivery_region_zone_rates
 FOR EACH ROW EXECUTE FUNCTION public.route_catalog_rate_audit();

-- Optional automatic timestamp on prices (independent of legacy route triggers).
CREATE OR REPLACE FUNCTION public.route_catalog_rate_stamp()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN NEW.updated_at := now(); NEW.updated_by := auth.uid(); RETURN NEW; END$$;
DROP TRIGGER IF EXISTS delivery_rates_stamp ON public.delivery_region_zone_rates;
CREATE TRIGGER delivery_rates_stamp BEFORE INSERT OR UPDATE ON public.delivery_region_zone_rates
 FOR EACH ROW EXECUTE FUNCTION public.route_catalog_rate_stamp();
COMMIT;
