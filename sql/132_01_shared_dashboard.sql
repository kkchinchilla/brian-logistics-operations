-- 1.3.2 Shared attendance + vehicle-owner mapping. No resets, no sample data.
BEGIN;
CREATE TABLE IF NOT EXISTS public.vehicle_owner_bindings (
 id bigint generated by default as identity primary key,
 driver_id uuid not null references public.profiles(id),
 vehicle_id bigint not null references public.vehicles(id),
 effective_from date not null default current_date,
 effective_to date,
 note text,
 created_at timestamptz not null default now(),
 CHECK(effective_to is null or effective_to>=effective_from),
 UNIQUE(vehicle_id,effective_from)
);
CREATE INDEX IF NOT EXISTS vehicle_owner_driver_idx ON public.vehicle_owner_bindings(driver_id);
CREATE OR REPLACE FUNCTION public.guard_vehicle_binding_overlap() RETURNS trigger
 LANGUAGE plpgsql SET search_path = '' AS $$BEGIN
 IF EXISTS (SELECT 1 FROM public.vehicle_owner_bindings x WHERE x.vehicle_id=NEW.vehicle_id AND x.id<>COALESCE(NEW.id,-1)
 AND daterange(x.effective_from,COALESCE(x.effective_to,'infinity'::date),'[]') && daterange(NEW.effective_from,COALESCE(NEW.effective_to,'infinity'::date),'[]')) THEN
 RAISE EXCEPTION '同一車輛的綁定生效期間重疊'; END IF;
 RETURN NEW;END$$;
DROP TRIGGER IF EXISTS vehicle_binding_overlap ON public.vehicle_owner_bindings;
CREATE TRIGGER vehicle_binding_overlap BEFORE INSERT OR UPDATE ON public.vehicle_owner_bindings FOR EACH ROW EXECUTE FUNCTION public.guard_vehicle_binding_overlap();
ALTER TABLE public.vehicle_owner_bindings ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS vob_read ON public.vehicle_owner_bindings;
DROP POLICY IF EXISTS vob_write ON public.vehicle_owner_bindings;
CREATE POLICY vob_read ON public.vehicle_owner_bindings FOR SELECT TO authenticated USING (true);
CREATE POLICY vob_write ON public.vehicle_owner_bindings FOR ALL TO authenticated USING ((SELECT private.is_dispatcher())) WITH CHECK ((SELECT private.is_dispatcher()));
GRANT SELECT,INSERT,UPDATE,DELETE ON public.vehicle_owner_bindings TO authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.vehicle_owner_bindings_id_seq TO authenticated;
-- Actual observations are stored independently from approved scheduled runs.
-- A driver can add observations only about their own existing assigned run.
CREATE TABLE IF NOT EXISTS public.daily_run_observations (
 id bigint generated by default as identity primary key,
 run_id bigint not null unique references public.runs(id) ON DELETE RESTRICT,
 driver_id uuid not null references public.profiles(id),
 actual_vehicle_id bigint references public.vehicles(id),
 actual_note text not null default '',
 updated_at timestamptz not null default now(),
 updated_by uuid references public.profiles(id)
);
CREATE OR REPLACE FUNCTION public.guard_daily_run_observation() RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
 DECLARE r record; BEGIN
 SELECT driver_id,service_date INTO r FROM public.runs WHERE id=NEW.run_id;
 IF NOT FOUND THEN RAISE EXCEPTION '找不到配送趟次'; END IF;
 IF NEW.driver_id IS DISTINCT FROM r.driver_id THEN RAISE EXCEPTION '不得修改其他司機的紀錄'; END IF;
 IF EXISTS(SELECT 1 FROM public.daily_attendance_closeouts WHERE service_date=r.service_date AND closed_at IS NOT NULL) THEN RAISE EXCEPTION '此日期已結案';END IF;
 IF NOT (SELECT private.is_dispatcher()) AND r.driver_id<>auth.uid() THEN RAISE EXCEPTION '無權修改該趟次'; END IF;
 NEW.updated_at:=now();NEW.updated_by:=auth.uid();RETURN NEW;
 END$$;
CREATE TABLE IF NOT EXISTS public.daily_attendance_closeouts (
 service_date date primary key,
 closed_at timestamptz,
 closed_by uuid references public.profiles(id),
 supervisor_note text not null default '',
 reopened_at timestamptz,
 reopen_reason text
);
DROP TRIGGER IF EXISTS daily_run_observation_guard ON public.daily_run_observations;
CREATE TRIGGER daily_run_observation_guard BEFORE INSERT OR UPDATE ON public.daily_run_observations FOR EACH ROW EXECUTE FUNCTION public.guard_daily_run_observation();
ALTER TABLE public.daily_run_observations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_attendance_closeouts ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS dro_read ON public.daily_run_observations;
DROP POLICY IF EXISTS dro_insert ON public.daily_run_observations;
DROP POLICY IF EXISTS dro_update ON public.daily_run_observations;
CREATE POLICY dro_read ON public.daily_run_observations FOR SELECT TO authenticated USING (true);
CREATE POLICY dro_insert ON public.daily_run_observations FOR INSERT TO authenticated WITH CHECK(driver_id=auth.uid() OR (SELECT private.is_dispatcher()));
CREATE POLICY dro_update ON public.daily_run_observations FOR UPDATE TO authenticated USING(driver_id=auth.uid() OR (SELECT private.is_dispatcher())) WITH CHECK(driver_id=auth.uid() OR (SELECT private.is_dispatcher()));
DROP POLICY IF EXISTS dac_read ON public.daily_attendance_closeouts;
DROP POLICY IF EXISTS dac_write ON public.daily_attendance_closeouts;
CREATE POLICY dac_read ON public.daily_attendance_closeouts FOR SELECT TO authenticated USING (true);
CREATE POLICY dac_write ON public.daily_attendance_closeouts FOR ALL TO authenticated USING((SELECT private.is_dispatcher())) WITH CHECK((SELECT private.is_dispatcher()));
GRANT SELECT,INSERT,UPDATE ON public.daily_run_observations,public.daily_attendance_closeouts TO authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.daily_run_observations_id_seq TO authenticated;
-- All company members may see names and route/vehicle dispatch data. Payroll remains restricted.
DROP POLICY IF EXISTS profiles_company_roster_read ON public.profiles;
CREATE POLICY profiles_company_roster_read ON public.profiles FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS runs_company_board_read ON public.runs;
CREATE POLICY runs_company_board_read ON public.runs FOR SELECT TO authenticated USING (true);
COMMIT;
-- A narrow RPC allows editing driver display names without permitting role changes.
CREATE OR REPLACE FUNCTION public.dashboard_rename_driver(p_driver uuid,p_name text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$BEGIN
 IF NOT (SELECT private.is_dispatcher()) THEN RAISE EXCEPTION '只有主管可修改司機姓名';END IF;
 IF p_name IS NULL OR length(btrim(p_name)) NOT BETWEEN 1 AND 70 THEN RAISE EXCEPTION '請輸入司機姓名';END IF;
 UPDATE public.profiles SET display_name=btrim(p_name) WHERE id=p_driver AND role='driver';
 IF NOT FOUND THEN RAISE EXCEPTION '找不到司機帳號';END IF;
END$$;
REVOKE ALL ON FUNCTION public.dashboard_rename_driver(uuid,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.dashboard_rename_driver(uuid,text) TO authenticated;
