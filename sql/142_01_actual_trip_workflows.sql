-- Prerequisites: 132, 140, 141 migrations. Run in a TEST project first.
-- Non-destructive: no DELETE, historical migration or payroll mutation.
BEGIN;

-- Revisions on planned runs also protect two supervisors editing the same assignment.
ALTER TABLE public.runs ADD COLUMN IF NOT EXISTS dashboard_schedule_revision integer NOT NULL DEFAULT 1;
CREATE OR REPLACE FUNCTION public.dashboard_bump_schedule_revision()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
BEGIN
 IF (OLD.service_date,OLD.route_id,OLD.driver_id,OLD.vehicle_id,OLD.is_rental,
     OLD.dispatcher_notes,OLD.attendance_category,OLD.attendance_slot_index,OLD.status)
   IS DISTINCT FROM
    (NEW.service_date,NEW.route_id,NEW.driver_id,NEW.vehicle_id,NEW.is_rental,
     NEW.dispatcher_notes,NEW.attendance_category,NEW.attendance_slot_index,NEW.status)
 THEN NEW.dashboard_schedule_revision := OLD.dashboard_schedule_revision+1;
 ELSE NEW.dashboard_schedule_revision := OLD.dashboard_schedule_revision;
 END IF;
 RETURN NEW;
END;$$;
DROP TRIGGER IF EXISTS dashboard_schedule_revision_trigger ON public.runs;
CREATE TRIGGER dashboard_schedule_revision_trigger BEFORE UPDATE ON public.runs
 FOR EACH ROW EXECUTE FUNCTION public.dashboard_bump_schedule_revision();

ALTER TABLE public.daily_run_observations
  ADD COLUMN IF NOT EXISTS actual_route_id bigint REFERENCES public.routes(id),
  ADD COLUMN IF NOT EXISTS revision integer NOT NULL DEFAULT 1;

CREATE TABLE IF NOT EXISTS public.daily_attendance_extra_trips (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 service_date date NOT NULL,
 driver_id uuid NOT NULL REFERENCES public.profiles(id),
 attendance_category text NOT NULL CHECK (attendance_category IN ('日配','OC','鮮二','冷凍','低鮮')),
 attendance_slot_index integer NOT NULL CHECK (attendance_slot_index BETWEEN 1 AND 30),
 actual_route_id bigint REFERENCES public.routes(id),
 actual_vehicle_id bigint REFERENCES public.vehicles(id),
 is_rental boolean,
 actual_note text NOT NULL DEFAULT '',
 status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','void')),
 revision integer NOT NULL DEFAULT 1 CHECK (revision >= 1),
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 created_by uuid REFERENCES public.profiles(id),
 updated_by uuid REFERENCES public.profiles(id),
 UNIQUE (service_date,driver_id,attendance_category,attendance_slot_index),
 CONSTRAINT extra_active_required_fields CHECK (
   status='void' OR (actual_route_id IS NOT NULL AND actual_vehicle_id IS NOT NULL AND is_rental IS NOT NULL)
 )
);
CREATE INDEX IF NOT EXISTS attendance_extra_service_date_idx
  ON public.daily_attendance_extra_trips(service_date);
ALTER TABLE public.daily_attendance_extra_trips ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS attendance_extra_company_read ON public.daily_attendance_extra_trips;
CREATE POLICY attendance_extra_company_read ON public.daily_attendance_extra_trips
 FOR SELECT TO authenticated USING(true);
REVOKE ALL ON public.daily_attendance_extra_trips FROM PUBLIC, anon;
GRANT SELECT ON public.daily_attendance_extra_trips TO authenticated;
-- Writes through validated RPCs ONLY. No direct UPDATE/INSERT/DELETE from clients.
REVOKE INSERT,UPDATE,DELETE ON public.daily_attendance_extra_trips FROM authenticated;
REVOKE INSERT,UPDATE,DELETE ON public.daily_run_observations FROM authenticated;

CREATE TABLE IF NOT EXISTS public.daily_attendance_change_log (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 happened_at timestamptz NOT NULL DEFAULT now(),
 actor_id uuid,
 record_type text NOT NULL CHECK(record_type IN ('observation','extra')),
 record_id bigint NOT NULL,
 operation text NOT NULL CHECK(operation IN ('INSERT','UPDATE')),
 old_value jsonb,
 new_value jsonb
);
ALTER TABLE public.daily_attendance_change_log ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS attendance_change_log_supervisors_read ON public.daily_attendance_change_log;
CREATE POLICY attendance_change_log_supervisors_read ON public.daily_attendance_change_log
 FOR SELECT TO authenticated USING ((SELECT private.is_dispatcher()));
REVOKE ALL ON public.daily_attendance_change_log FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.daily_attendance_change_log TO authenticated;

CREATE OR REPLACE FUNCTION public.dashboard_log_attendance_change()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
BEGIN
 INSERT INTO public.daily_attendance_change_log(actor_id,record_type,record_id,operation,old_value,new_value)
 VALUES(auth.uid(),CASE WHEN TG_TABLE_NAME='daily_run_observations' THEN 'observation' ELSE 'extra' END,
        NEW.id,TG_OP,CASE WHEN TG_OP='INSERT' THEN NULL ELSE pg_catalog.to_jsonb(OLD) END,pg_catalog.to_jsonb(NEW));
 RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS dashboard_log_daily_observation ON public.daily_run_observations;
CREATE TRIGGER dashboard_log_daily_observation AFTER INSERT OR UPDATE ON public.daily_run_observations
 FOR EACH ROW EXECUTE FUNCTION public.dashboard_log_attendance_change();
DROP TRIGGER IF EXISTS dashboard_log_extra_trip ON public.daily_attendance_extra_trips;
CREATE TRIGGER dashboard_log_extra_trip AFTER INSERT OR UPDATE ON public.daily_attendance_extra_trips
 FOR EACH ROW EXECUTE FUNCTION public.dashboard_log_attendance_change();

-- Existing guard still checks run ownership and closed-day protection. Add a
-- per-date lock to serialize closing a day against changing an actual run.
CREATE OR REPLACE FUNCTION public.guard_daily_run_observation() RETURNS trigger
 LANGUAGE plpgsql SET search_path='' AS $$
DECLARE r record;
BEGIN
 SELECT driver_id,service_date INTO r FROM public.runs WHERE id=NEW.run_id;
 IF NOT FOUND THEN RAISE EXCEPTION '找不到配送趟次'; END IF;
 PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(r.service_date::text));
 IF NEW.driver_id IS DISTINCT FROM r.driver_id THEN RAISE EXCEPTION '不得修改其他司機的紀錄'; END IF;
 IF EXISTS (SELECT 1 FROM public.daily_attendance_closeouts c WHERE c.service_date=r.service_date AND c.closed_at IS NOT NULL)
 THEN RAISE EXCEPTION '此日期已結案'; END IF;
 IF NOT (SELECT private.is_dispatcher()) AND r.driver_id<>auth.uid() THEN RAISE EXCEPTION '無權修改該趟次'; END IF;
 NEW.updated_at:=now();NEW.updated_by:=auth.uid();RETURN NEW;
END; $$;

-- Closing and reopening get the SAME date lock as live updates.
CREATE OR REPLACE FUNCTION public.dashboard_guard_closeout_lock() RETURNS trigger
 LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
BEGIN
 IF NOT (SELECT private.is_dispatcher()) THEN RAISE EXCEPTION '只有主管可結案或重新開啟';END IF;
 IF TG_OP='UPDATE' AND OLD.service_date<>NEW.service_date THEN RAISE EXCEPTION '不可變更結案日期';END IF;
 PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(NEW.service_date::text));
 RETURN NEW;
END;$$;
DROP TRIGGER IF EXISTS dashboard_daily_closeout_lock ON public.daily_attendance_closeouts;
CREATE TRIGGER dashboard_daily_closeout_lock BEFORE INSERT OR UPDATE ON public.daily_attendance_closeouts
 FOR EACH ROW EXECUTE FUNCTION public.dashboard_guard_closeout_lock();

-- Preserve the existing 140 safeguards, but serialize day changes as well.
CREATE OR REPLACE FUNCTION public.dashboard_guard_closed_run_day()
RETURNS trigger LANGUAGE plpgsql SET search_path='' AS $$
DECLARE old_date date; new_date date;
BEGIN
 IF TG_OP <> 'INSERT' THEN old_date:=OLD.service_date; END IF;
 IF TG_OP <> 'DELETE' THEN new_date:=NEW.service_date; END IF;
 IF old_date IS NOT NULL AND new_date IS NOT NULL AND old_date<>new_date THEN
   PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(LEAST(old_date,new_date)::text));
   PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(GREATEST(old_date,new_date)::text));
 ELSE
   PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(COALESCE(old_date,new_date)::text));
 END IF;
 IF (old_date IS NOT NULL AND EXISTS
   (SELECT 1 FROM public.daily_attendance_closeouts c WHERE c.service_date=old_date AND c.closed_at IS NOT NULL))
 OR (new_date IS NOT NULL AND EXISTS
   (SELECT 1 FROM public.daily_attendance_closeouts c WHERE c.service_date=new_date AND c.closed_at IS NOT NULL))
 THEN RAISE EXCEPTION '此出勤日期已結案；請先由主管重新開啟'; END IF;
 IF TG_OP='UPDATE' AND EXISTS
    (SELECT 1 FROM public.trip_executions e WHERE e.run_id=OLD.id AND e.review_status='confirmed')
    AND (OLD.service_date,OLD.route_id,OLD.driver_id,OLD.vehicle_id,OLD.is_rental)
      IS DISTINCT FROM (NEW.service_date,NEW.route_id,NEW.driver_id,NEW.vehicle_id,NEW.is_rental)
 THEN RAISE EXCEPTION '此趟次已確認，不得修改已確認的預排欄位';END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END;$$;

-- Preserve 141's column-count protection and include recorded extra trips.
CREATE OR REPLACE FUNCTION public.dashboard_guard_attendance_slot_count()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE highest integer;
BEGIN
 IF NOT (SELECT private.is_dispatcher()) THEN RAISE EXCEPTION '只有主管可調整每日趟數'; END IF;
 IF TG_OP='UPDATE' AND (OLD.service_date,OLD.category) IS DISTINCT FROM (NEW.service_date,NEW.category)
 THEN RAISE EXCEPTION '不可變更已儲存出勤欄位設定的日期或類別';END IF;
 PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(NEW.service_date::text));
 IF EXISTS (SELECT 1 FROM public.daily_attendance_closeouts c
   WHERE c.service_date=NEW.service_date AND c.closed_at IS NOT NULL)
 THEN RAISE EXCEPTION '此日期已結案，請先重新開啟';END IF;
 SELECT COALESCE(MAX(s),0) INTO highest FROM (
   SELECT MAX(attendance_slot_index) AS s FROM public.runs
    WHERE service_date=NEW.service_date AND attendance_category=NEW.category
   UNION ALL
   SELECT MAX(attendance_slot_index) AS s FROM public.daily_attendance_extra_trips
    WHERE service_date=NEW.service_date AND attendance_category=NEW.category AND status='active'
 ) x;
 IF NEW.slot_count<highest THEN RAISE EXCEPTION '%第 % 趟已有資料，不可減少至 % 趟',NEW.category,highest,NEW.slot_count;END IF;
 NEW.updated_at:=now();NEW.updated_by:=auth.uid();RETURN NEW;
END;$$;

-- A scheduled run and an extra actual run cannot occupy the same driver cell.
CREATE OR REPLACE FUNCTION public.dashboard_guard_attendance_slot_assignment()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE limit_slots integer;
BEGIN
 IF TG_OP='UPDATE' AND (OLD.attendance_category,OLD.attendance_slot_index) IS DISTINCT FROM
   (NEW.attendance_category,NEW.attendance_slot_index) AND EXISTS (
     SELECT 1 FROM public.trip_executions e WHERE e.run_id=OLD.id AND e.review_status='confirmed')
 THEN RAISE EXCEPTION '此趟次已確認，無法改動出勤類別或欄位';END IF;
 IF NEW.attendance_category IS NULL THEN RETURN NEW; END IF;
 IF NOT (SELECT private.is_dispatcher()) THEN RAISE EXCEPTION '只有主管可指定出勤欄位';END IF;
 PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(NEW.service_date::text));
 SELECT COALESCE((SELECT c.slot_count FROM public.daily_attendance_slot_counts c
  WHERE c.service_date=NEW.service_date AND c.category=NEW.attendance_category),
  public.dashboard_attendance_slot_base(NEW.attendance_category)) INTO limit_slots;
 IF NEW.attendance_slot_index>limit_slots THEN
   RAISE EXCEPTION '此日期的%目前只有%趟；請先調整趟數',NEW.attendance_category,limit_slots;
 END IF;
 IF EXISTS (SELECT 1 FROM public.daily_attendance_extra_trips x
   WHERE x.service_date=NEW.service_date AND x.driver_id=NEW.driver_id
     AND x.attendance_category=NEW.attendance_category
     AND x.attendance_slot_index=NEW.attendance_slot_index AND x.status='active')
 THEN RAISE EXCEPTION '此欄位已有臨時實際趟次，請先處理該紀錄';END IF;
 RETURN NEW;
END;$$;

-- Version=0 means "not yet created". Revision changes only through these RPCs.
-- A SECURITY DEFINER routine checks the authenticated identity and active profile
-- explicitly. Revoke direct client writes to prevent bypassing revision checks.
CREATE OR REPLACE FUNCTION public.dashboard_save_actual_observation(
 p_run_id bigint,p_actual_route_id bigint,p_actual_vehicle_id bigint,
 p_note text,p_expected_revision integer)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE assigned public.runs%ROWTYPE; existing_revision integer; out_revision integer;
BEGIN
 IF auth.uid() IS NULL OR NOT EXISTS (SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND p.active)
 THEN RAISE EXCEPTION '請使用有效帳號登入';END IF;
 IF p_expected_revision IS NULL OR p_expected_revision<0 THEN RAISE EXCEPTION '編輯版本無效';END IF;
 SELECT * INTO assigned FROM public.runs WHERE id=p_run_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION '找不到配送趟次，請重新整理';END IF;
 IF NOT (SELECT private.is_dispatcher()) AND assigned.driver_id<>auth.uid()
 THEN RAISE EXCEPTION '無權修改其他司機的出勤';END IF;
 PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(assigned.service_date::text));
 IF EXISTS (SELECT 1 FROM public.daily_attendance_closeouts
  WHERE service_date=assigned.service_date AND closed_at IS NOT NULL)
 THEN RAISE EXCEPTION '此出勤日期已結案';END IF;
 IF p_actual_route_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.routes WHERE id=p_actual_route_id)
 THEN RAISE EXCEPTION '找不到實際配送路線';END IF;
 IF p_actual_vehicle_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.vehicles WHERE id=p_actual_vehicle_id)
 THEN RAISE EXCEPTION '找不到實際使用車輛';END IF;
 IF length(COALESCE(p_note,''))>1000 THEN RAISE EXCEPTION '備註不可超過 1000 字';END IF;
 IF EXISTS (SELECT 1 FROM public.trip_executions e WHERE e.run_id=p_run_id AND e.review_status='confirmed')
 THEN RAISE EXCEPTION '此配送趟次已確認，須透過正式更正流程處理';END IF;
 SELECT revision INTO existing_revision FROM public.daily_run_observations WHERE run_id=p_run_id FOR UPDATE;
 IF p_expected_revision<>COALESCE(existing_revision,0) THEN RAISE EXCEPTION '資料已被其他人更新，請重新整理再編輯';END IF;
 IF existing_revision IS NULL THEN
   INSERT INTO public.daily_run_observations(run_id,driver_id,actual_route_id,actual_vehicle_id,actual_note,revision,updated_by)
    VALUES(p_run_id,assigned.driver_id,p_actual_route_id,p_actual_vehicle_id,COALESCE(p_note,''),1,auth.uid())
    RETURNING revision INTO out_revision;
 ELSE
   UPDATE public.daily_run_observations
   SET actual_route_id=p_actual_route_id,actual_vehicle_id=p_actual_vehicle_id,
       actual_note=COALESCE(p_note,''),revision=existing_revision+1,updated_by=auth.uid()
   WHERE run_id=p_run_id RETURNING revision INTO out_revision;
 END IF;
 RETURN out_revision;
END;$$;

CREATE OR REPLACE FUNCTION public.dashboard_save_extra_actual_trip(
 p_service_date date,p_driver_id uuid,p_category text,p_slot_index integer,
 p_route_id bigint,p_vehicle_id bigint,p_is_rental boolean,p_note text,
 p_expected_revision integer,p_void boolean DEFAULT false)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE old_rec public.daily_attendance_extra_trips%ROWTYPE; n integer; resulting_revision integer;
BEGIN
 IF auth.uid() IS NULL OR NOT EXISTS (SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND p.active)
 THEN RAISE EXCEPTION '請使用有效帳號登入';END IF;
 IF NOT (SELECT private.is_dispatcher()) AND auth.uid()<>p_driver_id
 THEN RAISE EXCEPTION '只可填寫自己的出勤資料';END IF;
 IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id=p_driver_id AND active AND role='driver')
 THEN RAISE EXCEPTION '此司機帳號不存在或未啟用';END IF;
 IF p_service_date IS NULL OR p_category IS NULL OR p_category NOT IN ('日配','OC','鮮二','冷凍','低鮮')
    OR p_slot_index IS NULL OR p_slot_index NOT BETWEEN 1 AND 30
 THEN RAISE EXCEPTION '出勤類別或欄位錯誤';END IF;
 IF p_expected_revision IS NULL OR p_expected_revision<0 THEN RAISE EXCEPTION '編輯版本無效';END IF;
 IF length(COALESCE(p_note,''))>1000 THEN RAISE EXCEPTION '備註不可超過 1000 字';END IF;
 PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(p_service_date::text));
 IF EXISTS (SELECT 1 FROM public.daily_attendance_closeouts
   WHERE service_date=p_service_date AND closed_at IS NOT NULL)
 THEN RAISE EXCEPTION '此出勤日期已結案';END IF;
 SELECT COALESCE((SELECT slot_count FROM public.daily_attendance_slot_counts
    WHERE service_date=p_service_date AND category=p_category),
    public.dashboard_attendance_slot_base(p_category)) INTO n;
 IF p_slot_index>n THEN RAISE EXCEPTION '此欄位已被移除，請重新整理';END IF;
 IF EXISTS(SELECT 1 FROM public.runs
   WHERE service_date=p_service_date AND driver_id=p_driver_id
     AND attendance_category=p_category AND attendance_slot_index=p_slot_index)
 THEN RAISE EXCEPTION '此欄位已有預排趟次，不能建立臨時趟次';END IF;
 SELECT * INTO old_rec FROM public.daily_attendance_extra_trips
  WHERE service_date=p_service_date AND driver_id=p_driver_id AND attendance_category=p_category
   AND attendance_slot_index=p_slot_index FOR UPDATE;
 IF p_expected_revision<>COALESCE(old_rec.revision,0)
 THEN RAISE EXCEPTION '資料已被其他人更新，請重新整理再編輯';END IF;
 IF COALESCE(p_void,false) AND old_rec.id IS NULL THEN RAISE EXCEPTION '找不到可撤銷的臨時趟次';END IF;
 IF COALESCE(p_void,false) AND NULLIF(btrim(COALESCE(p_note,'')),'') IS NULL
 THEN RAISE EXCEPTION '撤銷臨時趟次需填寫原因';END IF;
 IF NOT COALESCE(p_void,false) THEN
   IF p_route_id IS NULL OR p_vehicle_id IS NULL OR p_is_rental IS NULL
   THEN RAISE EXCEPTION '臨時趟次請填寫實際路線、車號及租車狀態';END IF;
   IF NOT EXISTS(SELECT 1 FROM public.routes WHERE id=p_route_id)
    OR NOT EXISTS(SELECT 1 FROM public.vehicles WHERE id=p_vehicle_id)
   THEN RAISE EXCEPTION '實際路線或車輛不存在';END IF;
 END IF;
 IF old_rec.id IS NULL THEN
  INSERT INTO public.daily_attendance_extra_trips
   (service_date,driver_id,attendance_category,attendance_slot_index,actual_route_id,
    actual_vehicle_id,is_rental,actual_note,status,created_by,updated_by)
  VALUES(p_service_date,p_driver_id,p_category,p_slot_index,p_route_id,p_vehicle_id,p_is_rental,
    COALESCE(p_note,''),'active',auth.uid(),auth.uid()) RETURNING revision INTO resulting_revision;
 ELSE
  UPDATE public.daily_attendance_extra_trips SET
    actual_route_id=CASE WHEN p_void THEN actual_route_id ELSE p_route_id END,
    actual_vehicle_id=CASE WHEN p_void THEN actual_vehicle_id ELSE p_vehicle_id END,
    is_rental=CASE WHEN p_void THEN is_rental ELSE p_is_rental END,
    actual_note=COALESCE(p_note,''),status=CASE WHEN p_void THEN 'void' ELSE 'active' END,
    revision=old_rec.revision+1,updated_at=now(),updated_by=auth.uid()
  WHERE id=old_rec.id RETURNING revision INTO resulting_revision;
 END IF;
 RETURN resulting_revision;
END;$$;
REVOKE ALL ON FUNCTION public.dashboard_save_actual_observation(bigint,bigint,bigint,text,integer) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.dashboard_save_extra_actual_trip(date,uuid,text,integer,bigint,bigint,boolean,text,integer,boolean) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.dashboard_save_actual_observation(bigint,bigint,bigint,text,integer) TO authenticated;
GRANT EXECUTE ON FUNCTION public.dashboard_save_extra_actual_trip(date,uuid,text,integer,bigint,bigint,boolean,text,integer,boolean) TO authenticated;
COMMIT;
