   WHERE c.service_date=NEW.service_date AND c.closed_at IS NOT NULL)
 THEN RAISE EXCEPTION '此日期已結案，請先重新開啟';END IF;
 SELECT COALESCE(MAX(s),0) INTO highest FROM (
   SELECT MAX(attendance_slot_index) AS s FROM public.runs
    WHERE service_date=NEW.service_date AND attendance_category=NEW.category
     AND (status::text<>'cancelled' OR EXISTS(SELECT 1 FROM public.daily_run_observations o WHERE o.run_id=public.runs.id))
   UNION ALL
   SELECT MAX(attendance_slot_index) AS s FROM public.daily_attendance_extra_trips
    WHERE service_date=NEW.service_date AND attendance_category=NEW.category AND status='active'
 ) x;
 IF NEW.slot_count<highest THEN RAISE EXCEPTION '%第 % 趟已有資料，不可減少至 % 趟',NEW.category,highest,NEW.slot_count;END IF;
 NEW.updated_at:=now();NEW.updated_by:=auth.uid();RETURN NEW;
END;$$;

