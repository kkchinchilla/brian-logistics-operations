CREATE OR REPLACE FUNCTION private.dashboard143_open_day(p_date date) RETURNS void
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
BEGIN
 IF p_date IS NULL THEN RAISE EXCEPTION '請指定有效日期';END IF;
 PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(p_date::text));
 IF EXISTS(SELECT 1 FROM public.daily_attendance_closeouts WHERE service_date=p_date AND closed_at IS NOT NULL)
 THEN RAISE EXCEPTION '此日期已結案，請先由主管重新開啟';END IF;
END;$$;
CREATE OR REPLACE FUNCTION private.dashboard143_has_runs(p_date date,p_driver uuid) RETURNS boolean
 LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT EXISTS(SELECT 1 FROM public.runs r WHERE r.service_date=p_date AND r.driver_id=p_driver
   AND (r.status::text<>'cancelled' OR EXISTS(SELECT 1 FROM public.daily_run_observations o WHERE o.run_id=r.id)))
 OR EXISTS(SELECT 1 FROM public.daily_attendance_extra_trips x WHERE x.service_date=p_date AND x.driver_id=p_driver AND x.status='active')
 OR EXISTS(SELECT 1 FROM public.trip_executions e WHERE e.service_date=p_date AND e.driver_id=p_driver);
$$;
