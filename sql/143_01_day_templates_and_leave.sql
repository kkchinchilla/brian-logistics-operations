-- A single scheduling write gate orders cross-date batch writes, leave, closeout,
-- actuals and run statements consistently. This is a technical serialization guard,
-- not a business rule about which drivers or vehicles may overlap.
CREATE OR REPLACE FUNCTION private.dashboard143_lock() RETURNS void
 LANGUAGE sql VOLATILE SECURITY DEFINER SET search_path='' AS $$
 SELECT pg_catalog.pg_advisory_xact_lock(20261020,143);
$$;
CREATE OR REPLACE FUNCTION private.dashboard143_statement_lock() RETURNS trigger
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
BEGIN PERFORM private.dashboard143_lock();RETURN NULL;END;$$;
DO $locks$
DECLARE t text;
BEGIN
 FOREACH t IN ARRAY ARRAY['runs','daily_run_observations','daily_attendance_extra_trips',
 'daily_attendance_closeouts','daily_attendance_slot_counts','trip_executions'] LOOP
  EXECUTE format('DROP TRIGGER IF EXISTS aaa_dashboard143_statement_lock ON public.%I',t);
  EXECUTE format('CREATE TRIGGER aaa_dashboard143_statement_lock BEFORE INSERT OR UPDATE OR DELETE ON public.%I FOR EACH STATEMENT EXECUTE FUNCTION private.dashboard143_statement_lock()',t);
 END LOOP;
END;$locks$;
