CREATE OR REPLACE FUNCTION private.dashboard143_normalize_rows(p_rows jsonb) RETURNS jsonb
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE x jsonb;outrows jsonb:='[]'::jsonb;k text;keys text[]:='{}';r public.routes%ROWTYPE;
 c text;n integer;rid bigint;vid bigint;
BEGIN
 IF p_rows IS NULL OR jsonb_typeof(p_rows)<>'array' OR jsonb_array_length(p_rows) NOT BETWEEN 1 AND 150
 THEN RAISE EXCEPTION '請建立 1 至 150 筆完整的單日預排趟次';END IF;
 FOR x IN SELECT value FROM jsonb_array_elements(p_rows) LOOP
  c:=x->>'category';
  IF jsonb_typeof(x)<>'object' OR c IS NULL OR c NOT IN ('日配','OC','鮮二','冷凍','低鮮')
   OR coalesce(x->>'slot_index','')!~'^[0-9]{1,2}$'
   OR coalesce(x->>'route_id','')!~'^[1-9][0-9]*$' OR coalesce(x->>'vehicle_id','')!~'^[1-9][0-9]*$'
   OR jsonb_typeof(x->'is_rental') IS DISTINCT FROM 'boolean'
  THEN RAISE EXCEPTION '每趟需指定出勤類別、欄位、路線、車號及是否租車';END IF;
  n:=(x->>'slot_index')::integer;rid:=(x->>'route_id')::bigint;vid:=(x->>'vehicle_id')::bigint;
  IF n NOT BETWEEN 1 AND 30 THEN RAISE EXCEPTION '出勤欄位序號須為 1–30';END IF;
  k:=c||':'||n;
  IF k=ANY(keys) THEN RAISE EXCEPTION '%第%趟重複',c,n;END IF;keys:=array_append(keys,k);
  SELECT * INTO r FROM public.routes WHERE id=rid AND active FOR SHARE;
  IF NOT FOUND OR r.temperature_zone IS NULL OR r.default_start_time IS NULL OR r.default_end_time IS NULL
   OR r.default_start_time=r.default_end_time THEN RAISE EXCEPTION '路線 % 未啟用或缺少固定溫層／時段',rid;END IF;
  IF NOT EXISTS(SELECT 1 FROM public.vehicles WHERE id=vid AND active) THEN RAISE EXCEPTION '車輛 % 不存在或未啟用',vid;END IF;
  outrows:=outrows||jsonb_build_array(jsonb_build_object('category',c,'slot_index',n,'route_id',rid,'vehicle_id',vid,'is_rental',(x->>'is_rental')::boolean));
 END LOOP;
 -- One driver cannot run two independent regular routes at the same time.
 IF EXISTS(SELECT 1 FROM jsonb_array_elements(outrows) WITH ORDINALITY a(x,i)
 JOIN jsonb_array_elements(outrows) WITH ORDINALITY b(x,i) ON a.i<b.i
 JOIN public.routes ar ON ar.id=(a.x->>'route_id')::bigint
 JOIN public.routes br ON br.id=(b.x->>'route_id')::bigint
 WHERE tsrange(date '2000-01-01'+ar.default_start_time,date '2000-01-01'+ar.default_end_time+CASE WHEN ar.default_end_time<ar.default_start_time THEN interval '1 day' ELSE interval '0 day' END,'[)')
 && tsrange(date '2000-01-01'+br.default_start_time,date '2000-01-01'+br.default_end_time+CASE WHEN br.default_end_time<br.default_start_time THEN interval '1 day' ELSE interval '0 day' END,'[)'))
 THEN RAISE EXCEPTION '單日範本包含重疊的固定路線時段';END IF;
 RETURN outrows;
END;$$;
CREATE OR REPLACE FUNCTION private.dashboard143_check_conflict(p_date date,p_driver uuid,p_vehicle bigint,p_route bigint,p_ignore bigint DEFAULT NULL) RETURNS void
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE r public.routes%ROWTYPE;hit bigint;
BEGIN
 SELECT * INTO r FROM public.routes WHERE id=p_route;
 SELECT q.id INTO hit FROM public.runs q JOIN public.routes qr ON qr.id=q.route_id
 WHERE q.id IS DISTINCT FROM p_ignore AND q.status::text<>'cancelled'
  AND (q.driver_id=p_driver OR q.vehicle_id=p_vehicle) AND q.service_date BETWEEN p_date-1 AND p_date+1
  AND tsrange(p_date+r.default_start_time,p_date+r.default_end_time+CASE WHEN r.default_end_time<r.default_start_time THEN interval '1 day' ELSE interval '0 day' END,'[)')
  && tsrange(q.service_date+coalesce(q.planned_start_time,qr.default_start_time),q.service_date+coalesce(q.planned_end_time,qr.default_end_time)
   +CASE WHEN coalesce(q.planned_end_time,qr.default_end_time)<coalesce(q.planned_start_time,qr.default_start_time) THEN interval '1 day' ELSE interval '0 day' END,'[)') LIMIT 1;
 IF hit IS NOT NULL THEN RAISE EXCEPTION '日期 % 的司機或車輛時段與趟次 #% 重疊（含跨日）',p_date,hit;END IF;
END;$$;

CREATE OR REPLACE FUNCTION public.dashboard_save_day_template(p_driver_id uuid,p_rows jsonb,p_expected_revision integer) RETURNS jsonb
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE current_rev integer;clean jsonb;outrec public.driver_day_templates%ROWTYPE;
BEGIN
 PERFORM private.dashboard143_lock();PERFORM private.dashboard143_require_dispatcher();PERFORM private.dashboard143_require_driver(p_driver_id);
 SELECT revision INTO current_rev FROM public.driver_day_templates WHERE driver_id=p_driver_id FOR UPDATE;
 IF p_expected_revision IS NULL OR p_expected_revision<>coalesce(current_rev,0) THEN RAISE EXCEPTION '範本已被其他人更新，請重新載入';END IF;
 clean:=private.dashboard143_normalize_rows(p_rows);
 INSERT INTO public.driver_day_templates(driver_id,rows,revision,updated_by) VALUES(p_driver_id,clean,1,auth.uid())
 ON CONFLICT(driver_id) DO UPDATE SET rows=excluded.rows,revision=public.driver_day_templates.revision+1,updated_at=now(),updated_by=auth.uid() RETURNING * INTO outrec;
 RETURN to_jsonb(outrec);
END;$$;
CREATE OR REPLACE FUNCTION public.dashboard_set_driver_leave(p_service_date date,p_driver_id uuid,p_is_leave boolean,p_expected_revision integer) RETURNS jsonb
