CREATE OR REPLACE FUNCTION private.dashboard143_touch_run() RETURNS trigger
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE changed boolean;
BEGIN
 IF TG_OP='UPDATE' THEN
  changed:=(OLD.service_date,OLD.driver_id,OLD.route_id,OLD.vehicle_id,OLD.is_rental,OLD.attendance_category,OLD.attendance_slot_index,OLD.dispatcher_notes,OLD.status::text='cancelled')
   IS DISTINCT FROM (NEW.service_date,NEW.driver_id,NEW.route_id,NEW.vehicle_id,NEW.is_rental,NEW.attendance_category,NEW.attendance_slot_index,NEW.dispatcher_notes,NEW.status::text='cancelled');
  IF (OLD.service_date,OLD.driver_id) IS DISTINCT FROM (NEW.service_date,NEW.driver_id)
  THEN PERFORM private.dashboard143_touch(OLD.service_date,OLD.driver_id,true);END IF;
  PERFORM private.dashboard143_touch(NEW.service_date,NEW.driver_id,changed);RETURN NEW;
 ELSIF TG_OP='DELETE' THEN PERFORM private.dashboard143_touch(OLD.service_date,OLD.driver_id,true);RETURN OLD;
 ELSE PERFORM private.dashboard143_touch(NEW.service_date,NEW.driver_id,true);RETURN NEW;END IF;
END;$$;
DROP TRIGGER IF EXISTS dashboard143_touch_run ON public.runs;
CREATE TRIGGER dashboard143_touch_run AFTER INSERT OR UPDATE OR DELETE ON public.runs FOR EACH ROW EXECUTE FUNCTION private.dashboard143_touch_run();
CREATE OR REPLACE FUNCTION private.dashboard143_guard_run() RETURNS trigger
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
BEGIN
 IF TG_OP='DELETE' THEN RETURN OLD;END IF;
 IF NEW.status::text<>'cancelled' AND EXISTS(SELECT 1 FROM public.attendance_driver_days d
  WHERE d.service_date=NEW.service_date AND d.driver_id=NEW.driver_id AND d.is_leave)
 THEN RAISE EXCEPTION '該司機當日已標示「休」，請先取消休假再新增趟次';END IF;
 IF TG_OP='UPDATE' THEN
  IF (OLD.driver_id,OLD.service_date) IS DISTINCT FROM (NEW.driver_id,NEW.service_date)
   AND (EXISTS(SELECT 1 FROM public.daily_run_observations WHERE run_id=OLD.id)
        OR EXISTS(SELECT 1 FROM public.trip_executions WHERE run_id=OLD.id))
  THEN RAISE EXCEPTION '已有實際出勤的預排不可移至其他司機或日期';END IF;
  IF NEW.status::text='cancelled' AND OLD.status::text<>'cancelled'
   AND EXISTS(SELECT 1 FROM public.trip_executions WHERE run_id=OLD.id)
  THEN RAISE EXCEPTION '此趟次已有實際執行紀錄，須先走既有更正流程';END IF;
  -- Pin inherited actual IDs BEFORE changing a planned assignment. Never let
  -- an observation with NULL=inherit silently switch to the newly planned route.
  IF (OLD.route_id,OLD.vehicle_id) IS DISTINCT FROM (NEW.route_id,NEW.vehicle_id) THEN
   UPDATE public.daily_run_observations SET actual_route_id=coalesce(actual_route_id,OLD.route_id),
    actual_vehicle_id=coalesce(actual_vehicle_id,OLD.vehicle_id),revision=revision+1
   WHERE run_id=OLD.id AND (actual_route_id IS NULL OR actual_vehicle_id IS NULL);
  END IF;
 END IF;
 IF NEW.status::text<>'cancelled' AND NEW.attendance_category IS NOT NULL
 AND EXISTS(SELECT 1 FROM public.runs r JOIN public.daily_run_observations o ON o.run_id=r.id
  WHERE r.id<>NEW.id AND r.service_date=NEW.service_date AND r.driver_id=NEW.driver_id
   AND r.attendance_category=NEW.attendance_category AND r.attendance_slot_index=NEW.attendance_slot_index)
 THEN RAISE EXCEPTION '此欄位已有獨立保留的實際出勤，請先確認該紀錄';END IF;
 RETURN NEW;
END;$$;
DROP TRIGGER IF EXISTS dashboard143_guard_run ON public.runs;
CREATE TRIGGER dashboard143_guard_run BEFORE INSERT OR UPDATE OR DELETE ON public.runs FOR EACH ROW EXECUTE FUNCTION private.dashboard143_guard_run();
CREATE OR REPLACE FUNCTION private.dashboard143_guard_actual() RETURNS trigger
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE d date;u uuid;
BEGIN
 IF TG_OP='DELETE' THEN RETURN OLD;END IF;
 IF TG_TABLE_NAME='daily_run_observations' THEN
  SELECT service_date,driver_id INTO d,u FROM public.runs WHERE id=NEW.run_id;
 ELSE d:=NEW.service_date;u:=NEW.driver_id;END IF;
 IF TG_TABLE_NAME='daily_attendance_extra_trips' THEN
  IF (to_jsonb(NEW)->>'status')='void' THEN RETURN NEW;END IF;
 END IF;
 IF EXISTS(SELECT 1 FROM public.attendance_driver_days WHERE service_date=d AND driver_id=u AND is_leave)
 THEN RAISE EXCEPTION '該司機當日已標示「休」，不可新增或回報趟次';END IF;
 RETURN NEW;
END;$$;
CREATE OR REPLACE FUNCTION private.dashboard143_touch_actual() RETURNS trigger
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE j jsonb;d date;u uuid;
BEGIN
 j:=CASE WHEN TG_OP='DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
 IF TG_TABLE_NAME='daily_run_observations' THEN SELECT service_date,driver_id INTO d,u FROM public.runs WHERE id=(j->>'run_id')::bigint;
 ELSE d:=(j->>'service_date')::date;u:=(j->>'driver_id')::uuid;END IF;
 PERFORM private.dashboard143_touch(d,u,false);
 IF TG_OP='DELETE' THEN RETURN OLD;END IF;RETURN NEW;
END;$$;
DO $actual$
DECLARE t text;
BEGIN
 FOREACH t IN ARRAY ARRAY['daily_run_observations','daily_attendance_extra_trips','trip_executions'] LOOP
  EXECUTE format('DROP TRIGGER IF EXISTS dashboard143_guard_actual ON public.%I',t);
  EXECUTE format('CREATE TRIGGER dashboard143_guard_actual BEFORE INSERT OR UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION private.dashboard143_guard_actual()',t);
  EXECUTE format('DROP TRIGGER IF EXISTS dashboard143_touch_actual ON public.%I',t);
  EXECUTE format('CREATE TRIGGER dashboard143_touch_actual AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION private.dashboard143_touch_actual()',t);
 END LOOP;
END;$actual$;

