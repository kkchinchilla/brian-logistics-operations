  UPDATE public.runs SET status='cancelled',dispatcher_notes=nullif(btrim(coalesce(p_note,'')),'') WHERE id=oldrun.id;
  RETURN jsonb_build_object('run_id',oldrun.id,'cancelled',true);
 END IF;
 clean:=private.dashboard143_normalize_rows(jsonb_build_array(jsonb_build_object('category',p_category,'slot_index',p_slot_index,'route_id',p_route_id,'vehicle_id',p_vehicle_id,'is_rental',p_is_rental)));
