CREATE OR REPLACE FUNCTION private.dashboard143_touch(p_date date,p_driver uuid,p_exception boolean) RETURNS void
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
BEGIN
 IF p_date IS NULL OR p_driver IS NULL THEN RETURN;END IF;
 INSERT INTO public.attendance_driver_days(service_date,driver_id,revision,has_plan_exception,updated_by)
 VALUES(p_date,p_driver,1,p_exception,auth.uid()) ON CONFLICT(service_date,driver_id) DO UPDATE SET
 revision=public.attendance_driver_days.revision+1,
 has_plan_exception=public.attendance_driver_days.has_plan_exception OR excluded.has_plan_exception,
 updated_at=now(),updated_by=auth.uid();
END;$$;
CREATE OR REPLACE FUNCTION private.dashboard143_log() RETURNS trigger
 LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE j jsonb;oldj jsonb;keyj jsonb;
BEGIN
 j:=CASE WHEN TG_OP='DELETE' THEN to_jsonb(OLD) ELSE to_jsonb(NEW) END;
 oldj:=CASE WHEN TG_OP='INSERT' THEN NULL ELSE to_jsonb(OLD) END;
 IF TG_OP='UPDATE' AND oldj=j THEN RETURN NEW;END IF;
