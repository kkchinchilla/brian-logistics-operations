-- Save one board cell as a planned run (empty pair means cancellation, not deletion).
CREATE OR REPLACE FUNCTION public.dashboard_save_day_plan(p_service_date date,p_driver_id uuid,p_category text,p_slot_index integer,
 p_route_id bigint,p_vehicle_id bigint,p_is_rental boolean,p_note text,p_run_id bigint,p_expected_run_revision integer,p_expected_day_revision integer)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE oldrun public.runs%ROWTYPE;d public.attendance_driver_days%ROWTYPE;outid bigint;clean jsonb;
BEGIN
 PERFORM private.dashboard143_lock();PERFORM private.dashboard143_require_dispatcher();PERFORM private.dashboard143_require_driver(p_driver_id);
 PERFORM private.dashboard143_open_day(p_service_date);
 SELECT * INTO d FROM public.attendance_driver_days WHERE service_date=p_service_date AND driver_id=p_driver_id FOR UPDATE;
 IF p_expected_day_revision IS NULL OR coalesce(d.revision,0)<>p_expected_day_revision THEN RAISE EXCEPTION '此日出勤已被更新，請重新整理後再編輯';END IF;
 IF coalesce(d.is_leave,false) THEN RAISE EXCEPTION '該司機當日已標示「休」，請先取消休假';END IF;
 IF p_category IS NULL OR p_category NOT IN ('日配','OC','鮮二','冷凍','低鮮') OR p_slot_index IS NULL OR p_slot_index NOT BETWEEN 1 AND 30
 THEN RAISE EXCEPTION '請指定有效的出勤欄位';END IF;
 IF length(coalesce(p_note,''))>1000 THEN RAISE EXCEPTION '備註不可超過 1000 字';END IF;
 IF p_run_id IS NOT NULL THEN
  SELECT * INTO oldrun FROM public.runs WHERE id=p_run_id FOR UPDATE;
  IF NOT FOUND OR (oldrun.service_date,oldrun.driver_id) IS DISTINCT FROM (p_service_date,p_driver_id)
   OR p_expected_run_revision IS NULL OR oldrun.dashboard_schedule_revision<>p_expected_run_revision
  THEN RAISE EXCEPTION '預排趟次已被更新，請重新整理後再編輯';END IF;
  IF oldrun.status::text NOT IN ('assigned','cancelled') OR EXISTS(SELECT 1 FROM public.trip_executions WHERE run_id=oldrun.id)
  THEN RAISE EXCEPTION '此趟次已執行或送審，須透過既有更正流程處理';END IF;
 END IF;
 IF p_route_id IS NULL AND p_vehicle_id IS NULL AND oldrun.id IS NULL THEN RETURN jsonb_build_object('unchanged',true);END IF;
 IF d.applied_rows IS NULL THEN
  INSERT INTO public.attendance_driver_days(service_date,driver_id,applied_rows) VALUES(p_service_date,p_driver_id,private.dashboard143_day_snapshot(p_service_date,p_driver_id))
  ON CONFLICT(service_date,driver_id) DO UPDATE SET applied_rows=excluded.applied_rows;
