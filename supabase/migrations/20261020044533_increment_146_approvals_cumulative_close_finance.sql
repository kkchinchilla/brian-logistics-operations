CREATE FUNCTION private.dashboard146_is_closed(p_date date) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT coalesce((SELECT max(id) FROM public.attendance_closeout_events WHERE action='close' AND through_date>=p_date),0)
 > coalesce((SELECT max(id) FROM public.attendance_closeout_events WHERE action='reopen' AND through_date=p_date),0)
 OR EXISTS(SELECT 1 FROM public.daily_attendance_closeouts WHERE service_date=p_date AND closed_at IS NOT NULL);
$$;
