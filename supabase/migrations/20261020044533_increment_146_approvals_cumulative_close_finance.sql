CREATE OR REPLACE FUNCTION private.dashboard143_open_day(p_date date) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
BEGIN
 IF p_date IS NULL THEN RAISE EXCEPTION '請指定有效日期';END IF;
 PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(p_date::text));
 IF private.dashboard146_is_closed(p_date) THEN RAISE EXCEPTION '此日期已結案，請先由主管填寫原因重新開啟';END IF;
END;$$;

CREATE FUNCTION private.dashboard146_guard_date() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE j jsonb; oldj jsonb; d date; oldd date;
BEGIN
 IF TG_OP<>'DELETE' THEN j:=to_jsonb(NEW);END IF;
 IF TG_OP<>'INSERT' THEN oldj:=to_jsonb(OLD);END IF;
 IF TG_TABLE_NAME='daily_run_observations' THEN
  SELECT service_date INTO d FROM public.runs WHERE id=(j->>'run_id')::bigint;
  SELECT service_date INTO oldd FROM public.runs WHERE id=(oldj->>'run_id')::bigint;
 ELSIF TG_TABLE_NAME='v055_driver_work_completions' THEN
  SELECT service_date INTO d FROM public.v055_run_work WHERE id=(j->>'work_id')::bigint;
  SELECT service_date INTO oldd FROM public.v055_run_work WHERE id=(oldj->>'work_id')::bigint;
 ELSE d:=(j->>'service_date')::date;oldd:=(oldj->>'service_date')::date;END IF;
 IF (d IS NOT NULL AND private.dashboard146_is_closed(d)) OR (oldd IS NOT NULL AND private.dashboard146_is_closed(oldd))
 THEN RAISE EXCEPTION '此日期已結案，請先由主管填寫原因重新開啟';END IF;
 IF TG_OP='DELETE' THEN RETURN OLD;END IF;RETURN NEW;
END;$$;
REVOKE ALL ON FUNCTION private.dashboard146_guard_date() FROM PUBLIC,anon,authenticated;
DO $guards$
DECLARE t text;
BEGIN
 FOREACH t IN ARRAY ARRAY['runs','trip_executions','daily_run_observations','daily_attendance_extra_trips',
 'daily_attendance_slot_counts','attendance_driver_days','attendance_records','v055_run_work','v055_standby_shifts','v055_driver_work_completions'] LOOP
  EXECUTE format('DROP TRIGGER IF EXISTS aaa_dashboard143_statement_lock ON public.%I',t);
  EXECUTE format('CREATE TRIGGER aaa_dashboard143_statement_lock BEFORE INSERT OR UPDATE OR DELETE ON public.%I FOR EACH STATEMENT EXECUTE FUNCTION private.dashboard143_statement_lock()',t);
  EXECUTE format('CREATE TRIGGER aab_dashboard146_date_guard BEFORE INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION private.dashboard146_guard_date()',t);
 END LOOP;
END;$guards$;
-- Old cached clients cannot issue a single-date close or reasonless reopen.
REVOKE ALL ON public.daily_attendance_closeouts FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.daily_attendance_closeouts TO authenticated;
REVOKE TRUNCATE ON public.runs,public.trip_executions,public.daily_run_observations,
