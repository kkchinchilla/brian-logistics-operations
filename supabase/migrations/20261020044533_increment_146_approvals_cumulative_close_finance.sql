CREATE OR REPLACE FUNCTION public.dashboard_get_schedule_month(p_driver_id uuid, p_month date)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE answer jsonb;firstday date;
BEGIN
 PERFORM private.dashboard143_require_dispatcher();PERFORM private.dashboard143_require_driver(p_driver_id);
 IF p_month IS NULL THEN RAISE EXCEPTION '請指定月份';END IF;
 firstday:=date_trunc('month',p_month)::date;
 SELECT jsonb_agg(jsonb_build_object('date',g.d::date,'revision',coalesce(s.revision,0),'is_leave',coalesce(s.is_leave,false),
  'closed',private.dashboard146_is_closed(g.d::date),'has_runs',private.dashboard143_has_runs(g.d::date,p_driver_id),
  'has_plan_exception',coalesce(s.has_plan_exception,false),'template_revision',s.template_revision) ORDER BY g.d)
 INTO answer FROM generate_series(firstday::timestamp,firstday+interval '1 month'-interval '1 day',interval '1 day') g(d)
 LEFT JOIN public.attendance_driver_days s ON s.service_date=g.d::date AND s.driver_id=p_driver_id
 LEFT JOIN public.daily_attendance_closeouts c ON c.service_date=g.d::date;
 RETURN answer;
END;$function$

