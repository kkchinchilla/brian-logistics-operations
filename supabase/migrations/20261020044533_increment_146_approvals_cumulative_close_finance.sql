CREATE OR REPLACE FUNCTION public.protect_run_assignment()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin

    -- Dispatchers may edit anything
    if (select private.is_dispatcher()) then
        return new;
    end if;

    -- Drivers may only edit their own run
    if old.driver_id != (select auth.uid()) then
        raise exception 'You cannot update this run.';
    end if;

    -- Drivers cannot change assignment information
    if new.driver_id is distinct from old.driver_id
       or new.vehicle_id is distinct from old.vehicle_id
       or new.route_id is distinct from old.route_id
       or new.service_date is distinct from old.service_date
       or new.scheduled_time is distinct from old.scheduled_time
       or new.dispatcher_notes is distinct from old.dispatcher_notes
    then
        raise exception 'Drivers cannot modify dispatch assignments.';
    end if;

    -- Drivers may only move through these statuses
    if new.status not in ('in_progress', 'completed') then
        raise exception 'Drivers may only start or complete a run.';
    end if;

    -- Assigned must be started first
    if old.status = 'assigned'
       and new.status not in ('assigned', 'in_progress')
    then
        raise exception 'An assigned run must be started before completion.';
    end if;

    -- In-progress may only stay in-progress or complete
    if old.status = 'in_progress'
       and new.status not in ('in_progress', 'completed')
    then
        raise exception 'An in-progress run may only be completed.';
    end if;

    return new;

end;
$function$

