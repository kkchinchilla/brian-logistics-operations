CREATE FUNCTION public.dashboard_get_attendance_day_state(p_date date) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path='' AS $$
DECLARE result jsonb; closed boolean;
BEGIN
 IF NOT EXISTS(SELECT 1 FROM public.profiles WHERE id=auth.uid() AND active)
 THEN RAISE EXCEPTION '請先登入' USING ERRCODE='42501';END IF;
 IF p_date IS NULL THEN RAISE EXCEPTION '請指定日期';END IF;
 closed:=private.dashboard146_is_closed(p_date);
 SELECT to_jsonb(c) INTO result FROM public.daily_attendance_closeouts c WHERE service_date=p_date;
 result:=coalesce(result,jsonb_build_object('service_date',p_date));
 IF closed THEN
  result:=result||jsonb_build_object('closed_at',coalesce(
   (SELECT happened_at FROM public.attendance_closeout_events WHERE action='close' AND through_date>=p_date ORDER BY id DESC LIMIT 1),
   (SELECT closed_at FROM public.daily_attendance_closeouts WHERE service_date=p_date)));
 ELSE result:=result||jsonb_build_object('closed_at',NULL);END IF;
 RETURN result||jsonb_build_object('closed',closed);
END;$$;

CREATE FUNCTION public.dashboard_close_attendance_through(p_through_date date,p_note text DEFAULT '') RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE dates date[];snap jsonb;stamp timestamptz;event_id bigint;expired integer;
BEGIN
 PERFORM private.dashboard143_lock();PERFORM private.dashboard143_require_dispatcher();
 IF p_through_date IS NULL OR length(coalesce(p_note,''))>1000 THEN RAISE EXCEPTION '結案日期或備註不正確';END IF;
 SELECT coalesce(array_agg(d ORDER BY d),'{}'::date[]) INTO dates FROM (
  SELECT p_through_date d UNION SELECT service_date FROM public.runs UNION SELECT service_date FROM public.trip_executions
  UNION SELECT service_date FROM public.daily_attendance_extra_trips UNION SELECT service_date FROM public.attendance_driver_days
  UNION SELECT service_date FROM public.daily_attendance_slot_counts UNION SELECT service_date FROM public.attendance_records
  UNION SELECT service_date FROM public.v055_run_work UNION SELECT service_date FROM public.v055_standby_shifts
  UNION SELECT service_date FROM public.daily_attendance_closeouts
 ) known WHERE d<=p_through_date AND NOT private.dashboard146_is_closed(d);
 -- Preserve the exact current records at closing; pending proposals are not applied.
 SELECT jsonb_build_object(
  'runs',coalesce((SELECT jsonb_agg(to_jsonb(r) ORDER BY id) FROM public.runs r WHERE service_date=ANY(dates)),'[]'::jsonb),
  'trip_executions',coalesce((SELECT jsonb_agg(to_jsonb(r) ORDER BY id) FROM public.trip_executions r WHERE service_date=ANY(dates)),'[]'::jsonb),
  'observations',coalesce((SELECT jsonb_agg(to_jsonb(o) ORDER BY o.id) FROM public.daily_run_observations o JOIN public.runs r ON r.id=o.run_id WHERE r.service_date=ANY(dates)),'[]'::jsonb),
  'extra_trips',coalesce((SELECT jsonb_agg(to_jsonb(r) ORDER BY id) FROM public.daily_attendance_extra_trips r WHERE service_date=ANY(dates)),'[]'::jsonb),
  'driver_days',coalesce((SELECT jsonb_agg(to_jsonb(r) ORDER BY service_date,driver_id) FROM public.attendance_driver_days r WHERE service_date=ANY(dates)),'[]'::jsonb),
  'slot_counts',coalesce((SELECT jsonb_agg(to_jsonb(r) ORDER BY service_date,category) FROM public.daily_attendance_slot_counts r WHERE service_date=ANY(dates)),'[]'::jsonb),
  'attendance_records',coalesce((SELECT jsonb_agg(to_jsonb(r) ORDER BY id) FROM public.attendance_records r WHERE service_date=ANY(dates)),'[]'::jsonb),
  'special_work',coalesce((SELECT jsonb_agg(to_jsonb(r) ORDER BY id) FROM public.v055_run_work r WHERE service_date=ANY(dates)),'[]'::jsonb),
  'standby',coalesce((SELECT jsonb_agg(to_jsonb(r) ORDER BY id) FROM public.v055_standby_shifts r WHERE service_date=ANY(dates)),'[]'::jsonb),
  'special_completions',coalesce((SELECT jsonb_agg(to_jsonb(c) ORDER BY c.id) FROM public.v055_driver_work_completions c JOIN public.v055_run_work w ON w.id=c.work_id WHERE w.service_date=ANY(dates)),'[]'::jsonb)
 ) INTO snap;
 stamp:=clock_timestamp();
 INSERT INTO public.attendance_closeout_events(action,through_date,actor_id,happened_at,reason,affected_dates,snapshot)
 VALUES('close',p_through_date,auth.uid(),stamp,btrim(coalesce(p_note,'')),dates,snap) RETURNING id INTO event_id;
 INSERT INTO public.daily_attendance_closeouts(service_date,closed_at,closed_by,supervisor_note,reopened_at,reopen_reason)
 SELECT d,stamp,auth.uid(),btrim(coalesce(p_note,'')),NULL,NULL FROM unnest(dates) d
 ON CONFLICT(service_date) DO UPDATE SET closed_at=excluded.closed_at,closed_by=excluded.closed_by,
 supervisor_note=excluded.supervisor_note,reopened_at=NULL,reopen_reason=NULL;
 UPDATE public.attendance_change_requests SET status='stale',revision=revision+1,reviewed_by=auth.uid(),reviewed_at=stamp,
 review_reason='出勤已結案；未核准的變更未套用，重新開啟後請重新送審'
 WHERE service_date<=p_through_date AND status='pending';
 GET DIAGNOSTICS expired=ROW_COUNT;
 RETURN jsonb_build_object('event_id',event_id,'through_date',p_through_date,'closed_dates',dates,'expired_requests',expired);
END;$$;

CREATE FUNCTION public.dashboard_reopen_attendance_date(p_date date,p_reason text) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE stamp timestamptz;event_id bigint;
BEGIN
 PERFORM private.dashboard143_lock();PERFORM private.dashboard143_require_dispatcher();
 IF p_date IS NULL OR nullif(btrim(coalesce(p_reason,'')),'') IS NULL OR length(p_reason)>1000
 THEN RAISE EXCEPTION '重新開啟必須填寫原因（1–1000 字）';END IF;
 IF NOT private.dashboard146_is_closed(p_date) THEN RAISE EXCEPTION '此日期尚未結案';END IF;
 stamp:=clock_timestamp();
 INSERT INTO public.attendance_closeout_events(action,through_date,actor_id,happened_at,reason,affected_dates)
 VALUES('reopen',p_date,auth.uid(),stamp,btrim(p_reason),ARRAY[p_date]) RETURNING id INTO event_id;
 INSERT INTO public.daily_attendance_closeouts(service_date,closed_at,closed_by,reopened_at,reopen_reason)
 VALUES(p_date,NULL,NULL,stamp,btrim(p_reason)) ON CONFLICT(service_date) DO UPDATE
 SET closed_at=NULL,closed_by=NULL,reopened_at=stamp,reopen_reason=btrim(p_reason);
 RETURN jsonb_build_object('event_id',event_id,'date',p_date,'reopened',true);
END;$$;

-- Ordinary dispatcher corrections use this single atomic write path, including
-- completed/confirmed records on open dates. Financial formulas are unchanged.
CREATE OR REPLACE FUNCTION public.dashboard_edit_run_direct(
 p_run_id bigint,p_route_id bigint,p_vehicle_id bigint,p_note text,p_expected_run_revision integer,
 p_expected_observation_revision integer DEFAULT 0,p_cancel boolean DEFAULT false
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE r public.runs%ROWTYPE;o public.daily_run_observations%ROWTYPE;n integer;
BEGIN
 PERFORM private.dashboard143_lock();PERFORM private.dashboard143_require_dispatcher();
 SELECT * INTO r FROM public.runs WHERE id=p_run_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION '找不到配送趟次';END IF;
 PERFORM private.dashboard143_open_day(r.service_date);
 IF p_expected_run_revision IS NULL OR r.dashboard_schedule_revision<>p_expected_run_revision
 THEN RAISE EXCEPTION '趟次已被更新，請重新整理';END IF;
 IF EXISTS(SELECT 1 FROM public.attendance_driver_days WHERE service_date=r.service_date AND driver_id=r.driver_id AND is_leave)
 THEN RAISE EXCEPTION '此司機當日休假';END IF;
 IF r.status NOT IN ('assigned','in_progress','completed') THEN RAISE EXCEPTION '已取消趟次不可修改';END IF;
 IF coalesce(p_cancel,false) AND (r.status<>'assigned' OR EXISTS(SELECT 1 FROM public.trip_executions WHERE run_id=r.id))
 THEN RAISE EXCEPTION '只能取消尚未開始且沒有執行紀錄的趟次';END IF;
 IF NOT coalesce(p_cancel,false) AND (
  NOT EXISTS(SELECT 1 FROM public.routes WHERE id=p_route_id AND (active OR id=r.route_id))
  OR NOT EXISTS(SELECT 1 FROM public.vehicles WHERE id=p_vehicle_id AND (active OR id=r.vehicle_id)))
 THEN RAISE EXCEPTION '請選擇有效的路線與車輛';END IF;
 IF length(coalesce(p_note,''))>1000 THEN RAISE EXCEPTION '備註不可超過 1000 字';END IF;
 SELECT * INTO o FROM public.daily_run_observations WHERE run_id=r.id FOR UPDATE;
 IF p_expected_observation_revision IS NULL OR coalesce(o.revision,0)<>p_expected_observation_revision
 THEN RAISE EXCEPTION '出勤資料已被更新，請重新整理';END IF;
 PERFORM pg_catalog.set_config('app.dashboard146_run',auth.uid()::text||':'||r.id::text,true);
 IF o.id IS NOT NULL THEN DELETE FROM public.daily_run_observations WHERE id=o.id;END IF;
 IF coalesce(p_cancel,false) THEN
  UPDATE public.runs SET status='cancelled',dispatcher_notes=nullif(btrim(coalesce(p_note,'')),'')
  WHERE id=r.id RETURNING dashboard_schedule_revision INTO n;
 ELSE
  UPDATE public.runs SET route_id=p_route_id,vehicle_id=p_vehicle_id,dispatcher_notes=nullif(btrim(coalesce(p_note,'')),'')
  WHERE id=r.id RETURNING dashboard_schedule_revision INTO n;
  -- Keep actual execution identity, review status and completion notes. Ordinary
  -- route/vehicle corrections update the same execution; never add a second trip.
  UPDATE public.trip_executions e SET route_id=s.route_id,vehicle_id=s.vehicle_id,
   route_temperature_zone=s.temperature_zone_snapshot,route_start_time=s.planned_start_time,
   route_end_time=s.planned_end_time,route_code_snapshot=s.route_code_snapshot,
   updated_at=clock_timestamp()
  FROM public.runs s WHERE s.id=r.id AND e.run_id=s.id AND e.driver_id=s.driver_id
   AND ROW(e.route_id,e.vehicle_id,e.route_temperature_zone,e.route_start_time,e.route_end_time,e.route_code_snapshot)
    IS DISTINCT FROM ROW(s.route_id,s.vehicle_id,s.temperature_zone_snapshot,s.planned_start_time,s.planned_end_time,s.route_code_snapshot);
 END IF;
 PERFORM pg_catalog.set_config('app.dashboard146_run','',true);
 RETURN jsonb_build_object('run_id',r.id,'revision',n,'cancelled',coalesce(p_cancel,false));
END;$$;

CREATE FUNCTION public.dashboard_request_attendance_change(
 p_run_id bigint,p_extra_trip_id bigint,p_route_id bigint,p_vehicle_id bigint,p_note text,
 p_expected_revision integer,p_expected_observation_revision integer DEFAULT 0,p_void boolean DEFAULT false
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE r public.runs%ROWTYPE;x public.daily_attendance_extra_trips%ROWTYPE;o public.daily_run_observations%ROWTYPE;
 d date;owner_id uuid;base jsonb;execution jsonb;request_row public.attendance_change_requests%ROWTYPE;
BEGIN
 PERFORM private.dashboard143_lock();
 IF NOT EXISTS(SELECT 1 FROM public.profiles WHERE id=auth.uid() AND active AND role='driver')
 THEN RAISE EXCEPTION '只有司機可送出本人趟次變更' USING ERRCODE='42501';END IF;
 IF num_nonnulls(p_run_id,p_extra_trip_id)<>1 THEN RAISE EXCEPTION '請指定一筆配送紀錄';END IF;
 IF p_run_id IS NOT NULL THEN
  SELECT * INTO r FROM public.runs WHERE id=p_run_id FOR UPDATE;
  IF NOT FOUND OR r.driver_id<>auth.uid() THEN RAISE EXCEPTION '只能修改本人的趟次' USING ERRCODE='42501';END IF;
  IF r.status NOT IN ('assigned','in_progress','completed') OR coalesce(p_void,false) THEN RAISE EXCEPTION '此趟次不能送出變更';END IF;
  SELECT * INTO o FROM public.daily_run_observations WHERE run_id=r.id;
  IF p_expected_revision IS NULL OR r.dashboard_schedule_revision<>p_expected_revision
   OR p_expected_observation_revision IS NULL OR coalesce(o.revision,0)<>p_expected_observation_revision
  THEN RAISE EXCEPTION '出勤資料已被更新，請重新整理';END IF;
  d:=r.service_date;owner_id:=r.driver_id;
  base:=jsonb_build_object('route_id',coalesce(o.actual_route_id,r.route_id),'vehicle_id',coalesce(o.actual_vehicle_id,r.vehicle_id),
   'note',coalesce(o.actual_note,r.dispatcher_notes,''),'status',r.status);
  SELECT to_jsonb(e) INTO execution FROM public.trip_executions e WHERE run_id=r.id;
 ELSE
  SELECT * INTO x FROM public.daily_attendance_extra_trips WHERE id=p_extra_trip_id FOR UPDATE;
  IF NOT FOUND OR x.driver_id<>auth.uid() THEN RAISE EXCEPTION '只能修改本人的趟次' USING ERRCODE='42501';END IF;
  IF x.status<>'active' OR p_expected_revision IS NULL OR x.revision<>p_expected_revision
  THEN RAISE EXCEPTION '臨時趟次已被更新，請重新整理';END IF;
  d:=x.service_date;owner_id:=x.driver_id;
  base:=jsonb_build_object('route_id',x.actual_route_id,'vehicle_id',x.actual_vehicle_id,'note',x.actual_note,'status',x.status);
 END IF;
 PERFORM private.dashboard143_open_day(d);
 IF NOT coalesce(p_void,false) AND (NOT EXISTS(SELECT 1 FROM public.routes WHERE id=p_route_id AND (active OR id=(base->>'route_id')::bigint))
  OR NOT EXISTS(SELECT 1 FROM public.vehicles WHERE id=p_vehicle_id AND (active OR id=(base->>'vehicle_id')::bigint)))
 THEN RAISE EXCEPTION '請選擇有效的路線與車輛';END IF;
 IF length(coalesce(p_note,''))>1000 OR (coalesce(p_void,false) AND nullif(btrim(coalesce(p_note,'')),'') IS NULL)
 THEN RAISE EXCEPTION '備註不可超過 1000 字；撤銷時需填寫原因';END IF;
 SELECT * INTO request_row FROM public.attendance_change_requests WHERE status='pending'
 AND ((p_run_id IS NOT NULL AND run_id=p_run_id) OR (p_extra_trip_id IS NOT NULL AND extra_trip_id=p_extra_trip_id)) FOR UPDATE;
 IF FOUND THEN
  IF request_row.source_revision=p_expected_revision AND request_row.observation_revision=coalesce(p_expected_observation_revision,0)
   AND request_row.proposed_route_id IS NOT DISTINCT FROM p_route_id AND request_row.proposed_vehicle_id IS NOT DISTINCT FROM p_vehicle_id
   AND request_row.proposed_note=coalesce(p_note,'') AND request_row.proposed_void=coalesce(p_void,false)
  THEN RETURN jsonb_build_object('id',request_row.id,'status','pending','revision',request_row.revision);END IF;
  RAISE EXCEPTION '此趟已有待審核變更，請先等待主管處理';
 END IF;
 INSERT INTO public.attendance_change_requests(run_id,extra_trip_id,service_date,driver_id,source_revision,observation_revision,
 base_record,base_execution,proposed_route_id,proposed_vehicle_id,proposed_note,proposed_void,requested_by)
 VALUES(p_run_id,p_extra_trip_id,d,owner_id,p_expected_revision,coalesce(p_expected_observation_revision,0),base,execution,
 p_route_id,p_vehicle_id,coalesce(p_note,''),coalesce(p_void,false),auth.uid()) RETURNING * INTO request_row;
 RETURN jsonb_build_object('id',request_row.id,'status','pending','revision',request_row.revision);
END;$$;

CREATE FUNCTION public.dashboard_review_attendance_change(p_request_id bigint,p_expected_revision integer,p_approve boolean,p_reason text DEFAULT '')
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE q public.attendance_change_requests%ROWTYPE;r public.runs%ROWTYPE;x public.daily_attendance_extra_trips%ROWTYPE;
 observation_version integer;execution jsonb;stale boolean:=false;
BEGIN
 PERFORM private.dashboard143_lock();PERFORM private.dashboard143_require_dispatcher();
 SELECT * INTO q FROM public.attendance_change_requests WHERE id=p_request_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION '找不到變更申請';END IF;
 IF q.status<>'pending' THEN RETURN jsonb_build_object('id',q.id,'status',q.status,'already_reviewed',true);END IF;
 IF p_expected_revision IS NULL OR q.revision<>p_expected_revision THEN RAISE EXCEPTION '申請已被更新，請重新整理';END IF;
 IF p_approve IS NULL OR length(coalesce(p_reason,''))>1000 THEN RAISE EXCEPTION '審核內容不正確';END IF;
 PERFORM private.dashboard143_open_day(q.service_date);
 IF NOT p_approve AND nullif(btrim(coalesce(p_reason,'')),'') IS NULL THEN RAISE EXCEPTION '退回時請填寫原因';END IF;
 IF p_approve THEN
  IF q.run_id IS NOT NULL THEN
   SELECT * INTO r FROM public.runs WHERE id=q.run_id FOR UPDATE;
   SELECT coalesce(max(revision),0) INTO observation_version FROM public.daily_run_observations WHERE run_id=q.run_id;
   SELECT to_jsonb(e) INTO execution FROM public.trip_executions e WHERE run_id=q.run_id;
   stale:=r.id IS NULL OR r.driver_id<>q.driver_id OR r.service_date<>q.service_date OR r.status NOT IN ('assigned','in_progress','completed')
    OR r.dashboard_schedule_revision<>q.source_revision OR observation_version<>q.observation_revision OR execution IS DISTINCT FROM q.base_execution;
   IF NOT stale THEN PERFORM public.dashboard_edit_run_direct(q.run_id,q.proposed_route_id,q.proposed_vehicle_id,q.proposed_note,q.source_revision,q.observation_revision,false);END IF;
  ELSE
   SELECT * INTO x FROM public.daily_attendance_extra_trips WHERE id=q.extra_trip_id FOR UPDATE;
   stale:=x.id IS NULL OR x.driver_id<>q.driver_id OR x.service_date<>q.service_date OR x.revision<>q.source_revision OR x.status<>'active';
   IF NOT stale THEN PERFORM public.dashboard_save_extra_actual_trip(x.service_date,x.driver_id,x.attendance_category,x.attendance_slot_index,
    q.proposed_route_id,q.proposed_vehicle_id,private.dashboard144_rental(x.service_date,x.driver_id,q.proposed_vehicle_id),
    q.proposed_note,q.source_revision,q.proposed_void);END IF;
  END IF;
 END IF;
 UPDATE public.attendance_change_requests SET status=CASE WHEN stale THEN 'stale' WHEN p_approve THEN 'approved' ELSE 'rejected' END,
 revision=revision+1,reviewed_by=auth.uid(),reviewed_at=clock_timestamp(),
 review_reason=CASE WHEN stale THEN '原紀錄已變更；本次申請未套用，請重新送審' ELSE btrim(coalesce(p_reason,'')) END
 WHERE id=q.id RETURNING * INTO q;
 RETURN jsonb_build_object('id',q.id,'status',q.status,'reason',q.review_reason);
END;$$;

