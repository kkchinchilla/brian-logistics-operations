      and parent.planned_start_time is not null and parent.planned_end_time is not null
      and tsrange(parent.service_date+parent.planned_start_time,
          parent.service_date+parent.planned_end_time+
          case when parent.planned_end_time<parent.planned_start_time then interval '1 day' else interval '0 days' end,'[)')
          && tsrange(start_at,end_at,'[)') limit 1;
  if conflict_id is not null then raise exception '與已登記跟車／故障接替勤務 #% 時段衝突', conflict_id; end if;
