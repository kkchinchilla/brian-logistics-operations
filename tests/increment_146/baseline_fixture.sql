   SELECT MAX(attendance_slot_index) AS s FROM public.runs
    WHERE service_date=NEW.service_date AND attendance_category=NEW.category
     AND (status::text<>'cancelled' OR EXISTS(SELECT 1 FROM public.daily_run_observations o WHERE o.run_id=public.runs.id))
   UNION ALL
   SELECT MAX(attendance_slot_index) AS s FROM public.daily_attendance_extra_trips
    WHERE service_date=NEW.service_date AND attendance_category=NEW.category AND status='active'
 ) x;
 IF NEW.slot_count<highest THEN RAISE EXCEPTION '%第 % 趟已有資料，不可減少至 % 趟',NEW.category,highest,NEW.slot_count;END IF;
 NEW.updated_at:=now();NEW.updated_by:=auth.uid();RETURN NEW;
END;$function$
;
CREATE OR REPLACE FUNCTION public.dashboard_guard_closed_run_day()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
DECLARE old_date date; new_date date;
BEGIN
 IF TG_OP <> 'INSERT' THEN old_date:=OLD.service_date; END IF;
 IF TG_OP <> 'DELETE' THEN new_date:=NEW.service_date; END IF;
 IF old_date IS NOT NULL AND new_date IS NOT NULL AND old_date<>new_date THEN
   PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(LEAST(old_date,new_date)::text));
   PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(GREATEST(old_date,new_date)::text));
 ELSE
   PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(COALESCE(old_date,new_date)::text));
 END IF;
 IF (old_date IS NOT NULL AND EXISTS
   (SELECT 1 FROM public.daily_attendance_closeouts c WHERE c.service_date=old_date AND c.closed_at IS NOT NULL))
 OR (new_date IS NOT NULL AND EXISTS
   (SELECT 1 FROM public.daily_attendance_closeouts c WHERE c.service_date=new_date AND c.closed_at IS NOT NULL))
 THEN RAISE EXCEPTION '此出勤日期已結案；請先由主管重新開啟'; END IF;
 IF TG_OP='UPDATE' AND EXISTS
    (SELECT 1 FROM public.trip_executions e WHERE e.run_id=OLD.id AND e.review_status='confirmed')
    AND (OLD.service_date,OLD.route_id,OLD.driver_id,OLD.vehicle_id,OLD.is_rental)
      IS DISTINCT FROM (NEW.service_date,NEW.route_id,NEW.driver_id,NEW.vehicle_id,NEW.is_rental)
 THEN RAISE EXCEPTION '此趟次已確認，不得修改已確認的預排欄位';END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END;$function$
;
