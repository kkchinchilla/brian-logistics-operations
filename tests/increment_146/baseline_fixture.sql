CREATE OR REPLACE FUNCTION public.v05512_reconcile_replacement_execution(p_work_id bigint, p_reason text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  w public.v055_run_work%rowtype;
  original public.runs%rowtype;
  execution public.trip_executions%rowtype;
  audit_id bigint;
  actor uuid:=auth.uid();
begin
  if actor is null or not private.is_dispatcher() then
    raise exception '僅主管可稽核校正故障接替實際歸屬';
  end if;
  if p_work_id is null then raise exception '缺少故障接替勤務編號'; end if;
  if length(btrim(coalesce(p_reason,'')))<10 or length(p_reason)>1000 then
    raise exception '請填寫至少 10 字、最多 1000 字的校正原因';
  end if;
  select * into w from public.v055_run_work
    where id=p_work_id for update;
  if not found or w.kind<>'breakdown_replacement' or w.review_status='rejected' then
    raise exception '找不到有效故障接替勤務';
  end if;
  if not exists (
    select 1 from public.v055_driver_work_completions c
    where c.work_id=w.id and c.driver_id=w.driver_id
  ) then raise exception '接替司機沒有完成回報'; end if;
  select * into original from public.runs where id=w.run_id for share;
  if not found or original.status<>'completed' then
    raise exception '原始主線尚未完成';
  end if;
  select * into execution from public.trip_executions
    where run_id=w.run_id for update;
  if not found or execution.review_status='rejected' then
    raise exception '找不到可校正的實際趟次（或已退回）';
  end if;
  if exists (
    select 1 from public.monthly_settlements ms
    where ms.month_start=date_trunc('month',execution.service_date)::date
      and ms.status='closed'
  ) then
    raise exception '此月已結算封存，不可直接校正；請使用正式月結更正流程';
  end if;
  if execution.driver_id=w.driver_id and execution.vehicle_id=w.vehicle_id then
    return jsonb_build_object('execution_id',execution.id,'state','already_correct');
  end if;
  if execution.driver_id is distinct from original.driver_id
     or execution.vehicle_id is distinct from original.vehicle_id then
    raise exception '實際趟次不是原派車快照，請先人工稽核；不可自動覆寫';
  end if;
  insert into public.v05512_execution_attribution_corrections(
    execution_id,replacement_work_id,original_driver_id,original_vehicle_id,
    corrected_driver_id,corrected_vehicle_id,explanation,corrected_by,correction_transaction_id
  ) values (
    execution.id,w.id,execution.driver_id,execution.vehicle_id,
    w.driver_id,w.vehicle_id,btrim(p_reason),actor,txid_current()
  ) returning id into audit_id;
  update public.trip_executions set driver_id=w.driver_id,vehicle_id=w.vehicle_id
    where id=execution.id;
  if not found then raise exception '校正失敗，未更新實際趟次'; end if;
  return jsonb_build_object('execution_id',execution.id,'audit_id',audit_id,'state','corrected');
end $function$
;
CREATE OR REPLACE FUNCTION public.v055_finalize_replacement(p_work_id bigint)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare w public.v055_run_work%rowtype;
        parent public.runs%rowtype;
begin
  if auth.uid() is null or not private.is_dispatcher() then
    raise exception '只有主管可以結束故障接替的原始趟次'; end if;
  select * into w from public.v055_run_work where id=p_work_id for update;
  if not found or w.kind<>'breakdown_replacement' or w.review_status<>'pending' then
    raise exception '無有效的待審核故障接替任務'; end if;
  if not exists(select 1 from public.v055_driver_work_completions c
      where c.work_id=w.id and c.driver_id=w.driver_id) then
    raise exception '接替司機尚未回報完成'; end if;
  select * into parent from public.runs where id=w.run_id for update;
  if parent.status not in ('assigned','in_progress') then
    raise exception '原始趟次必須仍在已指派／配送中狀態，請檢查是否已被其他人完成'; end if;
  if exists(select 1 from public.trip_executions e where e.run_id=parent.id) then
    raise exception '原始趟次已有實際執行紀錄，請先核對'; end if;
  update public.runs set status='completed' where id=w.run_id;
  -- Immutable audit of the supervisor reconciliation action.
  insert into public.v055_work_audit(table_name,source_id,action,old_record,new_record,actor)
  values('runs',parent.id,'FINALIZE_REPLACEMENT',
    jsonb_build_object('status',parent.status,'scheduled_driver_id',parent.driver_id),
    jsonb_build_object('status','completed','replacement_work_id',w.id,
                       'replacement_driver_id',w.driver_id,'replacement_vehicle_id',w.vehicle_id),
    auth.uid());
  return jsonb_build_object('run_id',parent.id,'state','pending_execution_review');
end $function$
;
