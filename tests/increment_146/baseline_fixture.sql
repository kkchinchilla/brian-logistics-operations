CREATE OR REPLACE FUNCTION private.v055_validate_run_work()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare src public.runs%rowtype; active_stage text; src_start time; src_end time;
    src_range tsrange; conflict_id bigint; lock_a bigint; lock_b bigint;
begin
  if not private.is_dispatcher() then raise exception '只有主管可以登記支援、接替或跟車'; end if;
  if tg_op='UPDATE' then
    if row(new.run_id,new.service_date,new.kind,new.driver_id,new.vehicle_id,new.standby_shift_id,
           new.follow_stage_snapshot,new.replacement_payee,new.support_reference,new.note,new.recorded_by,new.created_at)
       is distinct from row(old.run_id,old.service_date,old.kind,old.driver_id,old.vehicle_id,old.standby_shift_id,
           old.follow_stage_snapshot,old.replacement_payee,old.support_reference,old.note,old.recorded_by,old.created_at) then
      raise exception '特殊勤務來源資料不可直接修改；請退回並新增';
    end if;
    if old.review_status <> 'pending' and new.review_status is distinct from old.review_status then
      raise exception '此勤務已審核，不可直接重複審核';
    end if;
    if new.review_status='confirmed' and old.review_status is distinct from new.review_status then
      if not exists (select 1 from public.trip_executions e join public.runs r on r.id=e.run_id
          where e.run_id=new.run_id and e.review_status='confirmed' and r.status='completed') then
        raise exception '原始配送趟次尚未完成且確認，不能核准此特殊勤務';
      end if;
      if new.standby_shift_id is not null and not exists(
        select 1 from public.v055_standby_shifts s where s.id=new.standby_shift_id and s.review_status<>'rejected') then
        raise exception '關聯值班已被退回，無法核准';
      end if;
    end if;
    if new.review_status is distinct from old.review_status then
      new.reviewed_by:=auth.uid();new.reviewed_at:=clock_timestamp();
    else
      new.reviewed_by:=old.reviewed_by;new.reviewed_at:=old.reviewed_at;
    end if;
    new.updated_at:=clock_timestamp();
    return new;
  end if;
  if new.review_status<>'pending' or new.reviewed_by is not null or new.reviewed_at is not null then
    raise exception '新特殊勤務必須先進入待審核狀態'; end if;
  new.recorded_by:=auth.uid();new.created_at:=clock_timestamp();
  select * into src from public.runs where id=new.run_id for share;
  if not found or src.status='cancelled' then raise exception '原始趟次不存在或已取消'; end if;
  new.service_date:=src.service_date;
  src_start:=src.planned_start_time;src_end:=src.planned_end_time;
  if src_start is null or src_end is null or src_start=src_end then
    raise exception '此趟次缺少有效的原始固定時段，請檢查歷史資料';
  end if;
  src_range:=tsrange(src.service_date+src_start,
    src.service_date+src_end+case when src_end<src_start then interval '1 day' else interval '0 days' end,'[)');
  if not exists (select 1 from public.profiles p where p.id=new.driver_id and p.role='driver' and p.active) then
    raise exception '請選擇有效司機';
  end if;
  if new.kind='attached_support' then
    if new.driver_id<>src.driver_id or new.vehicle_id is distinct from src.vehicle_id then
      raise exception '附屬支援必須使用主線的同一位司機與車輛';
    end if;
    new.follow_stage_snapshot:=null;new.replacement_payee:=null;
    new.support_reference:=btrim(new.support_reference);
  elsif new.kind='breakdown_replacement' then
    if new.driver_id=src.driver_id or new.vehicle_id is null or new.vehicle_id=src.vehicle_id then
      raise exception '故障接替必須改派其他司機與其他車輛';
    end if;
    if new.replacement_payee not in ('replacement_only','both') or new.replacement_payee is null then
      raise exception '故障接替須選擇趟次歸屬（預設只計接替司機）';
    end if;
    new.follow_stage_snapshot:=null;new.support_reference:=null;
  elsif new.kind='follow_along' then
    if new.driver_id=src.driver_id or new.vehicle_id is distinct from src.vehicle_id then
      raise exception '跟車司機須不同於主線司機，並搭乘主線車輛';
    end if;
    select s.stage into active_stage from public.v055_driver_stages s
      where s.driver_id=new.driver_id and s.effective_from<=src.service_date
      order by s.effective_from desc limit 1;
    if active_stage is null then raise exception '請先設定跟車司機於配送當日的訓練／正式任職階段'; end if;
    new.follow_stage_snapshot:=active_stage;new.replacement_payee:=null;new.support_reference:=null;
    if new.standby_shift_id is not null then raise exception '跟車不可關聯值班班段'; end if;
  end if;
  -- If the driver has an overlapping standby shift, it must be explicitly
  -- associated. This avoids paying both standby and support for that shift.
  if new.kind in ('attached_support','breakdown_replacement')
     and new.standby_shift_id is null and exists(
        select 1 from public.v055_standby_shifts s
        where s.driver_id=new.driver_id and s.review_status<>'rejected'
          and tsrange(s.service_date+s.start_time,
              s.service_date+s.end_time+case when s.end_time<s.start_time then interval '1 day' else interval '0 days' end,'[)') && src_range)
  then raise exception '此司機有重疊值班班段，請明確選擇該班段以轉換支援'; end if;
  if new.standby_shift_id is not null then
    if not exists(select 1 from public.v055_standby_shifts s
      where s.id=new.standby_shift_id and s.driver_id=new.driver_id
        and s.review_status<>'rejected'
        and tsrange(s.service_date+s.start_time,
             s.service_date+s.end_time+case when s.end_time<s.start_time then interval '1 day' else interval '0 days' end,'[)') && src_range)
    then raise exception '關聯值班班段必須屬於同一司機並與此路線時段重疊'; end if;
  end if;
  -- A follow passenger or replacement driver cannot simultaneously drive another
  -- independent route. Attached support is explicitly nested in its parent.
  if new.kind in ('breakdown_replacement','follow_along') then
    lock_a:=pg_catalog.hashtextextended('dispatch-driver-'||new.driver_id::text,0);
    lock_b:=pg_catalog.hashtextextended('dispatch-vehicle-'||new.vehicle_id::text,0);
    perform pg_catalog.pg_advisory_xact_lock(least(lock_a,lock_b));
    if lock_a<>lock_b then perform pg_catalog.pg_advisory_xact_lock(greatest(lock_a,lock_b)); end if;
    select q.id into conflict_id from public.runs q
      join public.routes r on r.id=q.route_id
      where q.id<>src.id and q.driver_id=new.driver_id and q.status<>'cancelled'
        and coalesce(q.planned_start_time,r.default_start_time) is not null
        and coalesce(q.planned_end_time,r.default_end_time) is not null
        and tsrange(q.service_date+coalesce(q.planned_start_time,r.default_start_time),
          q.service_date+coalesce(q.planned_end_time,r.default_end_time)+
            case when coalesce(q.planned_end_time,r.default_end_time)<coalesce(q.planned_start_time,r.default_start_time)
            then interval '1 day' else interval '0 days' end,'[)') && src_range
      limit 1;
    if conflict_id is not null then raise exception '此司機已有衝突的獨立趟次 #%',conflict_id; end if;
    -- A separate replacement cannot use a vehicle on a different scheduled route.
    if new.kind='breakdown_replacement' then
      select q.id into conflict_id from public.runs q join public.routes r on r.id=q.route_id
        where q.id<>src.id and q.vehicle_id=new.vehicle_id and q.status<>'cancelled'
          and coalesce(q.planned_start_time,r.default_start_time) is not null
          and coalesce(q.planned_end_time,r.default_end_time) is not null
          and tsrange(q.service_date+coalesce(q.planned_start_time,r.default_start_time),
            q.service_date+coalesce(q.planned_end_time,r.default_end_time)+
            case when coalesce(q.planned_end_time,r.default_end_time)<coalesce(q.planned_start_time,r.default_start_time)
            then interval '1 day' else interval '0 days' end,'[)') && src_range limit 1;
      if conflict_id is not null then raise exception '接替車輛已有衝突趟次 #%',conflict_id; end if;
    end if;
    select w.id into conflict_id from public.v055_run_work w
      join public.runs q on q.id=w.run_id
      where w.review_status<>'rejected'
        and w.kind in ('follow_along','breakdown_replacement')
        and (w.driver_id=new.driver_id or (new.kind='breakdown_replacement' and w.kind='breakdown_replacement' and w.vehicle_id=new.vehicle_id))
        and tsrange(q.service_date+q.planned_start_time,
          q.service_date+q.planned_end_time+case when q.planned_end_time<q.planned_start_time then interval '1 day' else interval '0 days' end,'[)') && src_range
      limit 1;
    if conflict_id is not null then raise exception '司機或車輛已有重疊的跟車／接替勤務 #%',conflict_id; end if;
  end if;
  return new;
end $function$
;
CREATE OR REPLACE FUNCTION private.v055_validate_shift()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare conflicting_id bigint;
begin
  if not private.is_dispatcher() then raise exception '只有主管可以安排或審核值班'; end if;
  if tg_op='UPDATE' then
    if row(new.service_date,new.driver_id,new.start_time,new.end_time,new.note,new.recorded_by,new.created_at)
       is distinct from row(old.service_date,old.driver_id,old.start_time,old.end_time,old.note,old.recorded_by,old.created_at) then
      raise exception '值班原始排班不可直接修改；請退回並建立新紀錄';
    end if;
    if old.review_status <> 'pending' and new.review_status is distinct from old.review_status then
      raise exception '已審核值班不可直接重複審核';
    end if;
    if new.review_status is distinct from old.review_status then
      new.reviewed_by:=auth.uid(); new.reviewed_at:=clock_timestamp();
    else
      new.reviewed_by:=old.reviewed_by;new.reviewed_at:=old.reviewed_at;
    end if;
    new.updated_at:=clock_timestamp();
    return new;
  end if;
  if new.review_status<>'pending' or new.reviewed_by is not null or new.reviewed_at is not null then
    raise exception '新值班紀錄必須先進入待審核狀態'; end if;
  new.recorded_by:=auth.uid();new.created_at:=clock_timestamp();
  if not exists (select 1 from public.profiles p where p.id=new.driver_id and p.role='driver' and p.active) then
    raise exception '請選擇有效司機';
  end if;
  -- Reject overlapping standby blocks for the same driver, including midnight shifts.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('v055-shift-'||new.driver_id::text,0));
  select s.id into conflicting_id from public.v055_standby_shifts s
  where s.driver_id=new.driver_id and s.review_status<>'rejected'
    and tsrange(s.service_date+s.start_time,
        s.service_date+s.end_time + case when s.end_time<s.start_time then interval '1 day' else interval '0 days' end,'[)')
      && tsrange(new.service_date+new.start_time,
        new.service_date+new.end_time + case when new.end_time<new.start_time then interval '1 day' else interval '0 days' end,'[)')
  limit 1;
  if conflicting_id is not null then raise exception '司機值班時段重疊：班段 #%',conflicting_id; end if;
  return new;
end $function$
;
