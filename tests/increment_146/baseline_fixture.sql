CREATE OR REPLACE FUNCTION private.audit_finance_change()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  key text;
  before_data jsonb;
  after_data jsonb;
begin
  if tg_op = 'INSERT' then
    key := new.id::text;
    after_data := to_jsonb(new);
  elsif tg_op = 'DELETE' then
    key := old.id::text;
    before_data := to_jsonb(old);
  else
    key := new.id::text;
    before_data := to_jsonb(old);
    after_data := to_jsonb(new);
  end if;
  insert into public.finance_audit_logs(source_table,source_id,operation,old_record,new_record,actor)
  values(tg_table_name,key,tg_op,before_data,after_data,auth.uid());
  return case when tg_op = 'DELETE' then old else new end;
end;
$function$
;
