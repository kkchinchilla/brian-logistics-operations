CREATE OR REPLACE FUNCTION public.dashboard_apply_day_template(p_driver_id uuid, p_template_revision integer, p_dates date[], p_expected_days jsonb, p_overwrite boolean, p_request_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE t public.driver_day_templates%ROWTYPE;batch public.attendance_template_batches%ROWTYPE;
 d date;s public.attendance_driver_days%ROWTYPE;clean jsonb;x jsonb;r public.runs%ROWTYPE;
 request jsonb;result jsonb;applied jsonb:='[]';skipped jsonb:='[]';why text;cat text;lim integer;need integer;
BEGIN
 PERFORM private.dashboard143_lock();PERFORM private.dashboard143_require_dispatcher();PERFORM private.dashboard143_require_driver(p_driver_id);
 IF p_request_id IS NULL OR p_template_revision IS NULL OR p_dates IS NULL OR cardinality(p_dates)<1
  OR cardinality(p_dates)>366 OR array_position(p_dates,NULL) IS NOT NULL OR p_overwrite IS NULL
  OR p_expected_days IS NULL OR jsonb_typeof(p_expected_days)<>'object'
 THEN RAISE EXCEPTION '請選取日期（單次最多 366 天）並重新載入預覽';END IF;
 request:=jsonb_build_object('driver',p_driver_id,'revision',p_template_revision,'dates',(SELECT jsonb_agg(z.selected_date ORDER BY z.selected_date) FROM (SELECT DISTINCT unnest(p_dates) selected_date) z),
  'expected',p_expected_days,'overwrite',p_overwrite);
 SELECT * INTO batch FROM public.attendance_template_batches WHERE request_id=p_request_id;
 IF FOUND THEN
  IF batch.actor_id<>auth.uid() OR batch.request_payload<>request THEN RAISE EXCEPTION '此請求識別碼已用於另一筆操作';END IF;
  RETURN batch.result; -- retry after a lost response cannot duplicate runs
 END IF;
 SELECT * INTO t FROM public.driver_day_templates WHERE driver_id=p_driver_id FOR UPDATE;
 IF NOT FOUND OR t.revision<>p_template_revision THEN RAISE EXCEPTION '範本已被更新，請重新載入後再套用';END IF;
 clean:=private.dashboard143_normalize_rows(t.rows);
 FOR d IN SELECT DISTINCT unnest(p_dates) ORDER BY 1 LOOP
  SELECT * INTO s FROM public.attendance_driver_days WHERE service_date=d AND driver_id=p_driver_id FOR UPDATE;
  why:=NULL;
  IF EXISTS(SELECT 1 FROM public.daily_attendance_closeouts WHERE service_date=d AND closed_at IS NOT NULL) THEN why:='已結案';
  ELSIF coalesce(s.is_leave,false) THEN why:='休假';
  ELSIF NOT p_overwrite AND (coalesce(s.has_plan_exception,false) OR (s.template_revision IS NULL AND private.dashboard143_has_runs(d,p_driver_id))) THEN why:='保留單日調整';
  ELSIF EXISTS(SELECT 1 FROM public.runs WHERE service_date=d AND driver_id=p_driver_id AND status::text NOT IN ('assigned','cancelled'))
   OR EXISTS(SELECT 1 FROM public.trip_executions e LEFT JOIN public.runs er ON er.id=e.run_id
    WHERE (e.service_date=d AND e.driver_id=p_driver_id) OR (er.service_date=d AND er.driver_id=p_driver_id)) THEN why:='已有實際執行或送審紀錄';
  ELSIF private.dashboard143_has_special_links(d,p_driver_id) THEN why:='保留特殊勤務關聯的預排';
  ELSIF EXISTS(SELECT 1 FROM public.runs WHERE service_date=d AND driver_id=p_driver_id AND status::text<>'cancelled' AND attendance_category IS NULL) THEN why:='有未分類預排，請先指定欄位';
  ELSIF EXISTS(SELECT 1 FROM public.daily_attendance_extra_trips WHERE service_date=d AND driver_id=p_driver_id AND status='active') THEN why:='保留臨時實際趟次，請先人工確認';
  END IF;
  IF why IS NOT NULL THEN skipped:=skipped||jsonb_build_array(jsonb_build_object('date',d,'reason',why));CONTINUE;END IF;
  IF coalesce(p_expected_days->>d::text,'')!~'^[0-9]+$' OR (p_expected_days->>d::text)::integer<>coalesce(s.revision,0)
  THEN RAISE EXCEPTION '日期 % 已被更新；本批未寫入，請重新載入日期後再試',d;END IF;
  PERFORM private.dashboard143_open_day(d);
  -- Preserve each existing run ID (and its observations). Cancelling first avoids
  -- false conflicts while replacing two routes whose order has changed.
  UPDATE public.runs SET status='cancelled' WHERE service_date=d AND driver_id=p_driver_id AND status::text='assigned';
  FOREACH cat IN ARRAY ARRAY['日配','OC','鮮二','冷凍','低鮮'] LOOP
   SELECT coalesce(max((value->>'slot_index')::integer),0) INTO need FROM jsonb_array_elements(clean) WHERE value->>'category'=cat;
   SELECT coalesce((SELECT slot_count FROM public.daily_attendance_slot_counts WHERE service_date=d AND category=cat),public.dashboard_attendance_slot_base(cat)) INTO lim;
   IF need>lim THEN INSERT INTO public.daily_attendance_slot_counts(service_date,category,slot_count) VALUES(d,cat,need)
    ON CONFLICT(service_date,category) DO UPDATE SET slot_count=excluded.slot_count;END IF;
  END LOOP;
  FOR x IN SELECT value FROM jsonb_array_elements(clean) LOOP
   SELECT * INTO r FROM public.runs q WHERE q.service_date=d AND q.driver_id=p_driver_id
    AND q.attendance_category=x->>'category' AND q.attendance_slot_index=(x->>'slot_index')::integer
    ORDER BY EXISTS(SELECT 1 FROM public.daily_run_observations o WHERE o.run_id=q.id) DESC,q.id DESC LIMIT 1 FOR UPDATE;
   PERFORM private.dashboard143_check_conflict(d,p_driver_id,(x->>'vehicle_id')::bigint,(x->>'route_id')::bigint,r.id);
   IF r.id IS NULL THEN
    INSERT INTO public.runs(service_date,driver_id,route_id,vehicle_id,is_rental,status,attendance_category,attendance_slot_index)
    VALUES(d,p_driver_id,(x->>'route_id')::bigint,(x->>'vehicle_id')::bigint,(x->>'is_rental')::boolean,'assigned',x->>'category',(x->>'slot_index')::integer);
   ELSE
    UPDATE public.runs SET route_id=(x->>'route_id')::bigint,vehicle_id=(x->>'vehicle_id')::bigint,
     is_rental=(x->>'is_rental')::boolean,status='assigned' WHERE id=r.id;
   END IF;
  END LOOP;
  INSERT INTO public.attendance_driver_days(service_date,driver_id,revision,has_plan_exception,template_revision,applied_rows,updated_by)
   VALUES(d,p_driver_id,1,false,t.revision,clean,auth.uid()) ON CONFLICT(service_date,driver_id) DO UPDATE SET
   revision=public.attendance_driver_days.revision+1,has_plan_exception=false,template_revision=t.revision,applied_rows=clean,updated_at=now(),updated_by=auth.uid();
  applied:=applied||jsonb_build_array(d);
 END LOOP;
 result:=jsonb_build_object('request_id',p_request_id,'applied_dates',applied,'skipped',skipped,'template_revision',t.revision);
 INSERT INTO public.attendance_template_batches(request_id,driver_id,actor_id,request_payload,result) VALUES(p_request_id,p_driver_id,auth.uid(),request,result);
 RETURN result;
END;$function$
;
