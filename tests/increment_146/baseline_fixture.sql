 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
begin
  if auth.uid() is null or not exists (
       select 1 from public.profiles p
       where p.id=auth.uid() and p.role='driver' and p.active
  ) then raise exception '此帳號沒有司機勤務查詢權限'; end if;
  if p_day is null then raise exception '請先選擇日期'; end if;
  return query
    select w.id,w.run_id,w.service_date,w.kind,w.support_reference,w.note,
      w.review_status,w.follow_stage_snapshot,w.replacement_payee,
      coalesce(parent.route_code_snapshot,r.route_code)::text,r.route_name::text,
      coalesce(parent.temperature_zone_snapshot,r.temperature_zone)::text,
      parent.planned_start_time,parent.planned_end_time,
      v.plate_number::text,v.label::text,parent.status::text,c.completed_at,c.completion_note::text
    from public.v055_run_work w
    join public.runs parent on parent.id=w.run_id
    join public.routes r on r.id=parent.route_id
    left join public.vehicles v on v.id=w.vehicle_id
    left join public.v055_driver_work_completions c on c.work_id=w.id
    where w.driver_id=auth.uid() and w.service_date=p_day
      and w.review_status<>'rejected'
    order by parent.planned_start_time,w.id;
end $function$
;
CREATE OR REPLACE FUNCTION public.v055_submit_special_completion(p_work_id bigint, p_note text DEFAULT ''::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare w public.v055_run_work%rowtype;
        parent public.runs%rowtype;
        worker uuid:=auth.uid();
begin
  if worker is null or not exists(
      select 1 from public.profiles p where p.id=worker and p.role='driver' and p.active
  ) then raise exception '只有有效司機可以回報勤務完成'; end if;
  if p_work_id is null then raise exception '無效的特殊勤務編號'; end if;
  if length(coalesce(p_note,''))>2000 then raise exception '完成備註不得超過 2000 字'; end if;
  select * into w from public.v055_run_work where id=p_work_id for update;
  if not found or w.driver_id<>worker or w.review_status<>'pending' then
    raise exception '此勤務不是目前帳號可回報的待審核任務'; end if;
  select * into parent from public.runs where id=w.run_id for share;
  if not found or parent.status='cancelled' then raise exception '關聯主線已取消，請聯絡主管'; end if;
  if w.kind='breakdown_replacement' and parent.status='completed' then
    raise exception '原始趟次已完成，請主管核對是否已處理接替'; end if;
  if exists(select 1 from public.v055_driver_work_completions c where c.work_id=w.id) then
    raise exception '此勤務已回報完成，不可重複提交'; end if;
  insert into public.v055_driver_work_completions(work_id,driver_id,completion_note)
     values(w.id,worker,btrim(coalesce(p_note,'')));
  return jsonb_build_object('work_id',w.id,'run_id',w.run_id,'state','submitted');
end $function$
;
