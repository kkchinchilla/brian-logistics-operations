CREATE OR REPLACE FUNCTION private.dashboard143_guard_run()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
BEGIN
 IF TG_OP='DELETE' THEN RETURN OLD;END IF;
 IF NEW.status::text<>'cancelled' AND EXISTS(SELECT 1 FROM public.attendance_driver_days d
  WHERE d.service_date=NEW.service_date AND d.driver_id=NEW.driver_id AND d.is_leave)
 THEN RAISE EXCEPTION '該司機當日已標示「休」，請先取消休假再新增趟次';END IF;
 IF TG_OP='UPDATE' THEN
  IF (OLD.driver_id,OLD.service_date) IS DISTINCT FROM (NEW.driver_id,NEW.service_date)
   AND (EXISTS(SELECT 1 FROM public.daily_run_observations WHERE run_id=OLD.id)
        OR EXISTS(SELECT 1 FROM public.trip_executions WHERE run_id=OLD.id))
  THEN RAISE EXCEPTION '已有實際出勤的預排不可移至其他司機或日期';END IF;
  IF NEW.status::text='cancelled' AND OLD.status::text<>'cancelled'
   AND EXISTS(SELECT 1 FROM public.trip_executions WHERE run_id=OLD.id)
  THEN RAISE EXCEPTION '此趟次已有實際執行紀錄，須先走既有更正流程';END IF;
  -- Pin inherited actual IDs BEFORE changing a planned assignment. Never let
  -- an observation with NULL=inherit silently switch to the newly planned route.
  IF (OLD.route_id,OLD.vehicle_id) IS DISTINCT FROM (NEW.route_id,NEW.vehicle_id) THEN
   UPDATE public.daily_run_observations SET actual_route_id=coalesce(actual_route_id,OLD.route_id),
    actual_vehicle_id=coalesce(actual_vehicle_id,OLD.vehicle_id),revision=revision+1
   WHERE run_id=OLD.id AND (actual_route_id IS NULL OR actual_vehicle_id IS NULL);
  END IF;
 END IF;
 IF NEW.status::text<>'cancelled' AND NEW.attendance_category IS NOT NULL
 AND EXISTS(SELECT 1 FROM public.runs r JOIN public.daily_run_observations o ON o.run_id=r.id
  WHERE r.id<>NEW.id AND r.service_date=NEW.service_date AND r.driver_id=NEW.driver_id
   AND r.attendance_category=NEW.attendance_category AND r.attendance_slot_index=NEW.attendance_slot_index)
 THEN RAISE EXCEPTION '此欄位已有獨立保留的實際出勤，請先確認該紀錄';END IF;
 RETURN NEW;
END;$function$
;
