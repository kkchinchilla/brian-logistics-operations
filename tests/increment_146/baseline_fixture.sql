CREATE OR REPLACE FUNCTION public.dashboard_guard_attendance_slot_assignment()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
DECLARE limit_slots integer;
BEGIN
 IF NEW.status::text='cancelled' THEN RETURN NEW;END IF;
 IF TG_OP='UPDATE' AND (OLD.service_date,OLD.driver_id,OLD.attendance_category,OLD.attendance_slot_index) IS NOT DISTINCT FROM
 (NEW.service_date,NEW.driver_id,NEW.attendance_category,NEW.attendance_slot_index) AND OLD.status::text<>'cancelled' THEN RETURN NEW;END IF;
 IF TG_OP='UPDATE' AND (OLD.attendance_category,OLD.attendance_slot_index) IS DISTINCT FROM
   (NEW.attendance_category,NEW.attendance_slot_index) AND EXISTS (
     SELECT 1 FROM public.trip_executions e WHERE e.run_id=OLD.id AND e.review_status='confirmed')
 THEN RAISE EXCEPTION '此趟次已確認，無法改動出勤類別或欄位';END IF;
 IF NEW.attendance_category IS NULL THEN RETURN NEW; END IF;
 IF NOT (SELECT private.is_dispatcher()) THEN RAISE EXCEPTION '只有主管可指定出勤欄位';END IF;
 PERFORM pg_catalog.pg_advisory_xact_lock(20261019,pg_catalog.hashtext(NEW.service_date::text));
 SELECT COALESCE((SELECT c.slot_count FROM public.daily_attendance_slot_counts c
  WHERE c.service_date=NEW.service_date AND c.category=NEW.attendance_category),
  public.dashboard_attendance_slot_base(NEW.attendance_category)) INTO limit_slots;
 IF NEW.attendance_slot_index>limit_slots THEN
   RAISE EXCEPTION '此日期的%目前只有%趟；請先調整趟數',NEW.attendance_category,limit_slots;
 END IF;
 IF EXISTS (SELECT 1 FROM public.daily_attendance_extra_trips x
   WHERE x.service_date=NEW.service_date AND x.driver_id=NEW.driver_id
     AND x.attendance_category=NEW.attendance_category
     AND x.attendance_slot_index=NEW.attendance_slot_index AND x.status='active')
 THEN RAISE EXCEPTION '此欄位已有臨時實際趟次，請先處理該紀錄';END IF;
 RETURN NEW;
END;$function$
;
CREATE OR REPLACE FUNCTION public.dashboard_guard_attendance_slot_count()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
DECLARE highest integer;
BEGIN
 IF NOT (SELECT private.is_dispatcher()) THEN RAISE EXCEPTION '只有主管可調整每日趟數'; END IF;
 IF TG_OP='UPDATE' AND (OLD.service_date,OLD.category) IS DISTINCT FROM (NEW.service_date,NEW.category)
 THEN RAISE EXCEPTION '不可變更已儲存出勤欄位設定的日期或類別';END IF;
